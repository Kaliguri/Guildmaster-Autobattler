/* Модель Лаборатории: раздел — это ДАННЫЕ, а не разметка.
   Файл раздела экспортирует один SectionDef, каркас собирает из него страницу, оглавление, якоря,
   витрину, поиск и музей отклонённого. Иначе «Отклонённое» пришлось бы вести вторым списком
   руками, и он разошёлся бы с разделами на первой же правке.

   Типы здесь не для красоты: стендов будет за сотню, и опечатка в поле ошибается МОЛЧА — карточка
   просто уезжает не в ту корзину. Это ровно та боль, от которой в content/ личных сайтов стоит Zod. */

/** Что решено про стенд. Из него собирается корзина: принятое видно в разделе, отклонённое — ещё и в музее. */
export type StandStatus =
  | "accepted"   // принято Максом, канон
  | "rejected"   // проиграло: попадёт в музей отклонённого
  | "waiting"    // нарисовано, вердикта нет
  | "note";      // не развилка, а иллюстрация ситуации

/** Рисовалка стенда. Канвас, масштаб под DPI и очистку держит каркас — сюда приходит готовый
 *  контекст и ЛОГИЧЕСКИЙ размер сцены (не пиксели устройства). */
export type DrawFn = (ctx: CanvasRenderingContext2D, width: number, height: number) => void;

export interface StandDef {
  /** Кусок адреса: #/раздел/id. Без него на стенд нельзя дать ссылку и он не попадёт в поиск. */
  id: string;
  status: StandStatus;
  title: string;
  /** Своя надпись вместо стандартной по статусу («ситуация», «финал 1 · разрушение»). */
  tag?: string;
  /** Пояснение под заголовком. Допускает разметку: <b>, <code>, <br>. */
  note?: string;
  /** Пары «свойство · значение» моноширинным списком. */
  facts?: Array<[string, string]>;
  /** Вывод: чем этот вариант лучше или хуже. У принятого подсвечивается. */
  verdict?: string;
  /** Номер записи в journal-adr, например "2026-07-31/86". Сшивает картинку с «почему так». */
  decision?: string;
  /** Логический размер сцены. По умолчанию 320×280 в сетке и 480×330 в паре. */
  size?: [number, number];
  draw?: DrawFn;
}

export type Block =
  /** Заголовок второго уровня: попадает в оглавление и получает якорь. */
  | { kind: "head"; id: string; title: string; lede?: string }
  | { kind: "text"; html: string; cls?: string }
  | { kind: "note"; html: string }
  | { kind: "legend"; items: Array<{ color: string; text: string }> }
  /** Переключатель, который читает рисовалка через toggles.isOn(id). Заводится тогда, когда
   *  сам переключатель — предмет разбора (информационный слой по Z), а не удобство просмотра. */
  | { kind: "toggle"; id: string; label: string; note?: string; initial?: boolean }
  | { kind: "table"; head?: string[]; rows: string[][] }
  /** Сетка стендов (по три в ряд) либо пара крупных карточек. */
  | { kind: "stands"; items: StandDef[] }
  | { kind: "split"; items: StandDef[] }
  /** Блок, который раздел строит сам. Для содержимого, приходящего из данных: список со ссылками
   *  и фильтрами нельзя объявить литералом, а рисовать текст на canvas — терять и ссылки, и поиск
   *  по странице. Каркас даёт контейнер и больше ни во что не вмешивается. */
  | { kind: "live"; id: string; render: (host: HTMLElement) => void };

export interface SectionDef {
  id: string;
  title: string;
  /** Надстрочник над заголовком. По умолчанию «Лаборатория Guildmaster». */
  eyebrow?: string;
  lede?: string;
  /** Прятать транспорт показа, если в разделе нет ничего движущегося. */
  transport?: boolean;
  blocks: Block[];
}

export interface PageDef {
  id: string;
  title: string;
  /** Полка в шапке и на витрине. */
  group: string;
  blurb: string;
  /** Ленивая загрузка раздела. Литерал import() нарочно: так путь проверяет КОМПИЛЯТОР,
   *  а не браузер в рантайме. Раздел без файла (музей) объявляет load: null. */
  load: (() => Promise<{ default: SectionDef }>) | null;
  /** Знак на карточке витрины, когда живого превью нет. */
  icon?: string;
  /** Внешний адрес: раздел живёт отдельным приложением со своими данными и своим генератором.
   *  Втягивать его внутрь нельзя — он перестанет собираться своим скриптом. */
  href?: string;
}
