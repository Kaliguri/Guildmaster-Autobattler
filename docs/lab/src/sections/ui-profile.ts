/* Экран выбора профиля: три раскладки на выбор.

   Источник чисел — `Art_Dev/UI Refs/_teardowns/06-entry-service-coop.md` §1, где разобраны два рефа
   этого класса: Hades II (4 слота на подложке) и Slay the Spire (3 слота прямо на затемнённом
   меню). Всё, что здесь названо долей экрана, взято оттуда, а не придумано.

   Что в игре сейчас: `ProfileScreen.uxml` — вертикальная панель-лист, где слоты идут строками, а под
   ними живёт «Как меня видят» (ник, цвет, курсор). То есть у нашего профиля ДВЕ задачи, а у рефов
   одна: их профиль это только слот сохранения. Отсюда третий вариант, которого в рефах нет. */

