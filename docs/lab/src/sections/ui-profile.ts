/** Карточка слота: шапка с именем, тело с бухгалтерией. Состав полей — выбор Макса 05.08.2026:
 *  «как Slay the Spire», то есть наиграно и когда трогали, без состояния забега. */
function slotCard(
  ctx: CanvasRenderingContext2D,
  r: w.Rect,
  width: number,
  height: number,
  state: "filled" | "empty" | "selected",
  index: number
): void {
  const lit = state === "selected";
  w.box(ctx, r, width, height, { lit, dashed: state === "empty" });

  // Шапка остаётся и у пустого слота (приём StS): пустая карточка отличается от заполненной только
  // телом, поэтому ряд читается как ряд, а не как «две карточки и дырка».
  const head: w.Rect = { x: r.x + 0.008, y: r.y + 0.02, w: r.w - 0.016, h: 0.05 };
  w.box(ctx, head, width, height, {
    label: `ПРОФИЛЬ ${index}`,
    size: 9,
    hollow: true,
    stroke: w.WIRE.line
  });

  if (state === "empty") {
    w.text(ctx, "пусто", { x: r.x + r.w / 2, y: r.y + r.h / 2 }, width, height, {
      align: "center",
      size: 10,
      color: w.WIRE.dim
    });
    return;
  }

  // Бухгалтерия по центру карточки, низ пустой — так у StS, и это не случайность: пустой низ
  // оставляет место кнопке удаления, которая висит ПОД карточкой, а не внутри неё.
  // Дата укорочена до «3 авг, 19:24»: полная строка рефа не влезает в карточку 18.8% и обрезалась
  // серединой — а обрезанный текст в чертеже читается как решение, которого никто не принимал.
  const rows = ["Время в игре", "47:33:07", "Обновлён", "3 авг, 19:24"];
  rows.forEach((s, i) => {
    const isLabel = i % 2 === 0;
    w.text(
      ctx,
      s,
      { x: r.x + 0.014, y: r.y + 0.235 + i * 0.055 },
      width,
      height,
      { size: isLabel ? 8 : 10, color: isLabel ? w.WIRE.dim : w.WIRE.text }
    );
  });
}

/* ---------- А: ряд карточек прямо на затемнённом меню (реф Slay the Spire) ---------- */

function drawRow(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.6);

  w.text(ctx, "ВЫБЕРИТЕ ПРОФИЛЬ", { x: 0.5, y: 0.15 }, width, height, {
    align: "center",
    size: 13
  });

  // Три карточки: ширина 21.7%, высота 50%, зазор 2.6% — числа рефа StS.
  const top = 0.25;
  const cw = 0.217;
  const gap = 0.026;
  const total = cw * 3 + gap * 2;
  const left = (1 - total) / 2;

  for (let i = 0; i < 3; i++) {
    const r: w.Rect = { x: left + i * (cw + gap), y: top, w: cw, h: 0.5 };
    slotCard(ctx, r, width, height, i === 0 ? "selected" : i === 1 ? "filled" : "empty", i + 1);
  }

  // Каретик над выбранным — знак выбора у StS; сама карточка при этом не подсвечена.
  const cx = (left + cw / 2) * width;
  ctx.fillStyle = w.WIRE.accent;
  ctx.beginPath();
  ctx.moveTo(cx - 6, top * height - 12);
  ctx.lineTo(cx + 6, top * height - 12);
  ctx.lineTo(cx, top * height - 4);
  ctx.closePath();
  ctx.fill();

  // Удаление — ПОД выбранной карточкой, отдельной кнопкой. Так у обоих рефов, и в обоих оно
  // показано только под тем слотом, что под курсором.
  w.trash(ctx, { x: left + cw / 2 - 0.017, y: top + 0.5 + 0.021, w: 0.034, h: 0.061 }, width, height);
  w.callout(
    ctx,
    { x: left + cw / 2 + 0.02, y: top + 0.55 },
    { x: left + cw / 2 + 0.09, y: top + 0.58 },
    "удалить — только под выбранным",
    width,
    height
  );

  w.box(ctx, { x: 0.02, y: 0.86, w: 0.09, h: 0.06 }, width, height, { label: "Назад", size: 9 });
  // Мерят ТРЕТЬЮ карточку: над первой стоит каретик выбора, а под рядом — кнопка удаления, и линия
  // налезала то на одно, то на другое. Карточки одинаковые, поэтому мерить можно любую.
  w.measure(ctx, { x: left + 2 * (cw + gap), y: top, w: cw, h: 0.5 }, "21.7%", width, height, "x", "before");
}

/* ---------- Б: ряд на подложке-листе (реф Hades II) ---------- */

function drawSheet(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.45);

  // Подложка 83.2% x 84.3% — числа рефа Hades II.
  const sheet: w.Rect = { x: 0.084, y: 0.096, w: 0.832, h: 0.843 };
  w.box(ctx, sheet, width, height, {});

  w.text(ctx, "ПРОФИЛЬ", { x: 0.5, y: 0.155 }, width, height, { align: "center", size: 12 });
  w.text(
    ctx,
    "строка-инструкция: что такое профиль и что он хранит",
    { x: 0.5, y: 0.195 },
    width,
    height,
    { align: "center", size: 8, color: w.WIRE.dim }
  );

  // Четыре слота: 18.8% x 52.8%, зазор 0.9%.
  const cw = 0.188;
  const gap = 0.009;
  const total = cw * 4 + gap * 3;
  const left = (1 - total) / 2;
  for (let i = 0; i < 4; i++) {
    const r: w.Rect = { x: left + i * (cw + gap), y: 0.271, w: cw, h: 0.528 };
    slotCard(ctx, r, width, height, i === 1 ? "selected" : i < 2 ? "filled" : "empty", i + 1);
  }

  w.trash(
    ctx,
    { x: left + (cw + gap) + cw / 2 - 0.014, y: 0.271 + 0.528 + 0.026, w: 0.028, h: 0.05 },
    width,
    height
  );

  w.box(ctx, { x: 0.458, y: 0.911, w: 0.084, h: 0.05 }, width, height, { label: "Назад", size: 9 });
  // Над подложкой, а не под ней: под её нижней кромкой уже кромка самого кадра.
  w.measure(ctx, sheet, "83.2%", width, height, "x", "before");
}

/* ---------- В: две зоны — слоты и идентичность на одном экране ---------- */

function drawSplit(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.55);

  w.text(ctx, "ПРОФИЛЬ", { x: 0.07, y: 0.12 }, width, height, { size: 13 });

  // Слева — колонка слотов: карточки лежат стопкой, а не рядом, потому что справа нужна половина
  // ширины под идентичность.
  for (let i = 0; i < 3; i++) {
    const r: w.Rect = { x: 0.07, y: 0.22 + i * 0.19, w: 0.36, h: 0.155 };
    w.box(ctx, r, width, height, {
      lit: i === 0,
      dashed: i === 2,
      label: i === 2 ? "пустой слот" : `ПРОФИЛЬ ${i + 1}`,
      sub: i === 2 ? undefined : "47:33:07 · 3 авг 2026",
      size: 10
    });
    if (i === 0) w.trash(ctx, { x: 0.385, y: 0.245, w: 0.03, h: 0.055 }, width, height);
  }

  // Справа — «как меня видят»: то, чего у рефов нет вовсе, потому что их профиль это только сейв.
  const right: w.Rect = { x: 0.5, y: 0.22, w: 0.43, h: 0.53 };
  w.box(ctx, right, width, height, { hollow: true });
  w.text(ctx, "КАК МЕНЯ ВИДЯТ", { x: 0.52, y: 0.26 }, width, height, { size: 10 });
  const rows: Array<[string, string]> = [
    ["Имя из Steam", "тумблер"],
    ["Ник", "поле ввода"],
    ["Цвет", "ряд образцов"],
    ["Курсор", "ряд образцов"]
  ];
  rows.forEach(([label, kind], i) => {
    const r: w.Rect = { x: 0.52, y: 0.31 + i * 0.1, w: 0.39, h: 0.075 };
    w.box(ctx, r, width, height, { label, sub: kind, size: 9 });
  });

  w.box(ctx, { x: 0.5, y: 0.79, w: 0.2, h: 0.06 }, width, height, { label: "Сохранить", lit: true, size: 9 });
  w.box(ctx, { x: 0.73, y: 0.79, w: 0.2, h: 0.06 }, width, height, { label: "Назад", size: 9 });
  // Меряем по нижней карточке стопки: над верхней линия налезла бы на заголовок, под верхней — на
  // соседнюю карточку.
  w.measure(ctx, { x: 0.07, y: 0.6, w: 0.36, h: 0.155 }, "36%", width, height);
}

