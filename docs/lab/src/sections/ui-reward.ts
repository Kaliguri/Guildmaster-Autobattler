/* Экран награды: три раскладки.

   Источник — `Art_Dev/UI Refs/_teardowns/04-reward-shop-choice.md`, девять рефов. Три наблюдения
   оттуда, которые важнее любой из раскладок:

     · РЯД — для крупных «личностей», КОЛОНКА — для строк-эффектов. Герои, режимы и товары стоят
       в ряд; дары Hades — в колонку. Ни один реф не ставит три большие карточки вертикально.
     · Кнопки «отказаться» нет ни у одного из девяти. Механизмы «не брать» — только платный
       перевыбор (Hades II) и фиксация слота (Brotato). У нас «Пропустить» есть, и это отклонение
       от класса: его надо либо оправдать, либо убрать.
     · Редкость никто не кодирует размером карточки или свечением по периметру. Свечение означает
       наведение. Единственный носитель, читаемый без легенды, — СЛОВО (Hades I и II).

   Что в игре сейчас: `RewardScreen.uxml` — панель с рядом вариантов, секция дропа и «Пропустить». */

