/** Карточка варианта: рамка, окно арта, имя, описание. Пропорции — из рефов, см. подписи. */
function choiceCard(
  ctx: CanvasRenderingContext2D,
  r: w.Rect,
  width: number,
  height: number,
  opts: { lit?: boolean; art?: number; name?: string; lines?: number; rarity?: string } = {}
): void {
  w.box(ctx, r, width, height, { lit: opts.lit });
  const artH = (opts.art ?? 0.5) * r.h;
  w.box(ctx, { x: r.x + 0.008, y: r.y + 0.02, w: r.w - 0.016, h: artH }, width, height, {
    hollow: true,
    dashed: true,
    label: "арт",
    size: 8
  });
  w.text(ctx, opts.name ?? "НАЗВАНИЕ", { x: r.x + r.w / 2, y: r.y + artH + 0.055 }, width, height, {
    align: "center",
    size: 10
  });
  if (opts.rarity) {
    w.text(ctx, opts.rarity, { x: r.x + r.w / 2, y: r.y + artH + 0.09 }, width, height, {
      align: "center",
      size: 8,
      color: w.WIRE.accent
    });
  }
  const lines = opts.lines ?? 3;
  for (let i = 0; i < lines; i++) {
    w.text(
      ctx,
      i === 0 ? "описание эффекта, числа" : "выделены по смыслу",
      { x: r.x + 0.012, y: r.y + artH + 0.13 + i * 0.032 },
      width,
      height,
      { size: 7, color: w.WIRE.dim }
    );
  }
}

/* ---------- А: ряд карточек, под каждой плашка последствия (реф Guildrun) ---------- */

function drawRowWithBanners(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.5);

  w.text(ctx, "НАГРАДА", { x: 0.5, y: 0.085 }, width, height, { align: "center", size: 12 });

  // Карточка 15.6% x 54.4%, зазор 9.4% — числа Guildrun. Верх карточек ровный, низ плашек рваный.
  const cw = 0.156;
  const gap = 0.094;
  const left = (1 - (cw * 3 + gap * 2)) / 2;
  for (let i = 0; i < 3; i++) {
    const x = left + i * (cw + gap);
    choiceCard(ctx, { x, y: 0.161, w: cw, h: 0.544 }, width, height, {
      lit: i === 2,
      art: 0.64,
      name: ["ЩИТ", "КЛИНОК", "ПОСОХ"][i],
      lines: 0
    });
    // Плашка последствия: верх у всех на 75.8%, высота по объёму текста — низ рваный намеренно.
    const bh = [0.064, 0.151, 0.16][i]!;
    w.box(ctx, { x: x - 0.041, y: 0.758, w: 0.238, h: bh }, width, height, {
      lit: i === 2,
      label: "что даёт этот выбор",
      size: 8
    });
  }
  w.callout(
    ctx,
    { x: left + 2 * (cw + gap) + cw / 2, y: 0.74 },
    { x: 0.52, y: 0.69 },
    "плашка окрашена как карточка: связь держит цвет",
    width,
    height,
    "right"
  );
  w.measure(ctx, { x: left, y: 0.161, w: cw, h: 0.544 }, "15.6%", width, height, "x", "before");
}

/* ---------- Б: колонка лежачих строк (рефы Hades I и II) ---------- */

function drawRows(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.55);

  w.text(ctx, "НАГРАДА", { x: 0.5, y: 0.1 }, width, height, { align: "center", size: 12 });

  // Строка 45.9% x 19.2%, зазор 1.4% высоты — числа Hades I. Иконка слева занимает ~22% площади.
  for (let i = 0; i < 3; i++) {
    const r: w.Rect = { x: 0.27, y: 0.22 + i * 0.206, w: 0.459, h: 0.192 };
    w.box(ctx, r, width, height, { lit: i === 1 });
    w.box(ctx, { x: r.x + 0.008, y: r.y + 0.022, w: 0.06, h: 0.148 }, width, height, {
      hollow: true,
      dashed: true,
      label: "◆",
      size: 12
    });
    w.text(ctx, ["ЩИТ ЗАСТАВЫ", "КЛИНОК ЗАРИ", "ПОСОХ ТИШИНЫ"][i]!, { x: 0.35, y: r.y + 0.05 }, width, height, {
      size: 10
    });
    // Редкость СЛОВОМ справа — единственный носитель, читаемый без знания легенды.
    w.text(ctx, ["обычная", "редкая", "обычная"][i]!, { x: r.x + r.w - 0.012, y: r.y + 0.05 }, width, height, {
      size: 8,
      align: "right",
      color: i === 1 ? w.WIRE.accent : w.WIRE.dim
    });
    w.text(ctx, "одна строка описания, ключевое слово выделено", { x: 0.35, y: r.y + 0.098 }, width, height, {
      size: 8,
      color: w.WIRE.dim
    });
    // Отдельная строка-стат: значение в фиксированной колонке на ~50% ширины строки.
    w.text(ctx, "‣ Урон:", { x: 0.35, y: r.y + 0.145 }, width, height, { size: 8, color: w.WIRE.dim });
    w.text(ctx, "50 ➜ 60", { x: 0.5, y: r.y + 0.145 }, width, height, { size: 9, color: w.WIRE.accent });
  }
  w.measure(ctx, { x: 0.27, y: 0.22, w: 0.459, h: 0.192 }, "45.9%", width, height, "x", "before");
}

/* ---------- В: ряд карточек, описание внутри (рефы STS2, Guildrun Update Cards) ---------- */

function drawSelfContained(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.6);

  w.text(ctx, "НАГРАДА", { x: 0.5, y: 0.085 }, width, height, { align: "center", size: 12 });

  // Карточка 18.1% x 64.6%, зазор 2.8% — числа STS2 Game Mode; блок центрирован точно.
  const cw = 0.181;
  const gap = 0.028;
  const left = (1 - (cw * 3 + gap * 2)) / 2;
  for (let i = 0; i < 3; i++) {
    choiceCard(ctx, { x: left + i * (cw + gap), y: 0.15, w: cw, h: 0.646 }, width, height, {
      lit: i === 0,
      art: 0.31,
      name: ["ЩИТ", "КЛИНОК", "ПОСОХ"][i],
      rarity: ["обычная", "редкая", "обычная"][i],
      lines: 4
    });
  }
  w.callout(
    ctx,
    { x: left + cw / 2, y: 0.8 },
    { x: 0.3, y: 0.86 },
    "нижняя четверть карточки пустая: цены и кнопок в ней нет",
    width,
    height
  );
  w.measure(ctx, { x: left, y: 0.15, w: cw, h: 0.646 }, "18.1%", width, height, "x", "before");
}

