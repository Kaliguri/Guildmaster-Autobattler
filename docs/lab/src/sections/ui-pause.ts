/* Экран паузы (ESC): три раскладки.

   Источник — `Art_Dev/UI Refs/_teardowns/02-settings-pause.md`, тот же разбор, что у настроек;
   ESC-меню в нём разобраны у Skul, Guildrun и Slay the Spire 2. Общего у класса немного, и это
   само по себе факт: пауза — самый свободный экран из всех, потому что состоит из четырёх-пяти
   строк и ничего больше.

   Единственное, что делают все трое: ПОДСВЕЧИВАЮТ НАВЕДЁННЫЙ ПУНКТ ЗАМЕТНО СИЛЬНЕЕ, чем на других
   экранах. У Guildrun это сплошная зелёная градиентная заливка вместо контура, у Skul — глифы
   светлее в 1.7 раза по замеру, у STS2 — плашка светлее соседних плюс золотая подпись. Причина
   понятна: пауза открывается вслепую, по клавише, и первый вопрос игрока — «где я сейчас».

   Что в игре сейчас: `PauseScreen.uxml` — «Продолжить», «Пригласить друга», «Настройки»,
   «В главное меню», «Выйти из игры». Пять пунктов, из них один кооповый. */

import * as w from "../lib/ui-wire.js";
import type { SectionDef } from "../types.js";

const ITEMS = ["Продолжить", "Пригласить друга", "Настройки", "В главное меню", "Выйти из игры"];

/* ---------- А: колонка по центру на затемнении ---------- */

function drawCenter(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.7);

  w.text(ctx, "ПАУЗА", { x: 0.5, y: 0.22 }, width, height, { align: "center", size: 14 });
  ITEMS.forEach((label, i) => {
    // Служебные пункты отбиты увеличенным зазором — тот же приём, что в главном меню.
    const gap = i >= 3 ? 0.03 : 0;
    w.box(ctx, { x: 0.4, y: 0.33 + i * 0.082 + gap, w: 0.2, h: 0.068 }, width, height, {
      label,
      size: 9,
      lit: i === 0
    });
  });
  w.callout(
    ctx,
    { x: 0.6, y: 0.36 },
    { x: 0.68, y: 0.29 },
    "наведённый пункт подсвечен сильно",
    width,
    height
  );
  w.measure(ctx, { x: 0.4, y: 0.33, w: 0.2, h: 0.068 }, "20%", width, height, "x", "before");
}

/* ---------- Б: колонка слева, как в главном меню ---------- */

function drawLeft(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.35);
  // Та же вуаль под колонкой, что в главном меню: приём повторяется, и пауза читается как его брат.
  const grad = ctx.createLinearGradient(0, 0, width * 0.85, 0);
  grad.addColorStop(0, "rgba(10,10,12,0.75)");
  grad.addColorStop(1, "rgba(10,10,12,0)");
  ctx.fillStyle = grad;
  ctx.fillRect(0, 0, width, height);

  w.text(ctx, "ПАУЗА", { x: 0.088, y: 0.33 }, width, height, { size: 13 });
  ITEMS.forEach((label, i) => {
    const gap = i >= 3 ? 0.024 : 0;
    w.box(ctx, { x: 0.088, y: 0.42 + i * 0.075 + gap, w: 0.167, h: 0.06 }, width, height, {
      label,
      size: 9,
      lit: i === 0
    });
  });
  w.callout(
    ctx,
    { x: 0.26, y: 0.45 },
    { x: 0.36, y: 0.38 },
    "тот же отступ и та же пластина, что в главном меню",
    width,
    height
  );
  w.measure(ctx, { x: 0.088, y: 0.42, w: 0.167, h: 0.06 }, "16.7%", width, height, "x", "before");
}

/* ---------- В: полоса поперёк кадра ---------- */

function drawBar(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.45);

  // Пункты лежат одной строкой поперёк кадра: бой почти не закрыт, а пауза читается как оверлей.
  w.box(ctx, { x: 0, y: 0.44, w: 1, h: 0.13 }, width, height, {});
  const total = 0.86;
  const cw = total / ITEMS.length;
  ITEMS.forEach((label, i) => {
    w.box(ctx, { x: 0.07 + i * cw, y: 0.465, w: cw - 0.015, h: 0.08 }, width, height, {
      label,
      size: 8,
      lit: i === 0
    });
  });
  w.text(ctx, "ПАУЗА", { x: 0.5, y: 0.36 }, width, height, { align: "center", size: 13 });
  w.callout(
    ctx,
    { x: 0.5, y: 0.6 },
    { x: 0.56, y: 0.7 },
    "бой виден почти целиком: закрыто 13% высоты",
    width,
    height
  );
  w.measure(ctx, { x: 0, y: 0.44, w: 1, h: 0.13 }, "100% x 13%", width, height, "x", "before");
}

