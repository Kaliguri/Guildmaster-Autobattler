const NAMES = ["Ирма", "Кай", "Дан", "Сув"];
const RELICS = ["Антимаг", "Арканист", "", "Криомант"];
const ITEMS = [1, 2, 0, 1];

/** Куда встали подтабы полки. Вердикт Макса — «А, шапкой полки»; остальные два оставлены рядом,
 *  чтобы вердикт было видно на чём основан. */
type TabsAt = "shelf" | "under" | "top";

/** Верхняя навигация игры — первый ярус, «чей это раздел». Постоянна на всех вкладках. */
function topbar(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.text(ctx, "ASC IV · Акт 4 · Уровень 3/12", { x: 0.03, y: 0.03 }, width, height, {
    size: 7,
    color: w.WIRE.dim
  });
  ["КАРТА", "БОЙ", "ОТРЯД", "КОМПЕНДИУМ"].forEach((t, i) => {
    w.box(ctx, { x: 0.33 + i * 0.095, y: 0.012, w: 0.09, h: 0.036 }, width, height, {
      label: t,
      size: 7,
      lit: i === 2
    });
  });
  w.text(ctx, "100 ◇   2/2 ♥", { x: 0.97, y: 0.03 }, width, height, {
    size: 7,
    align: "right",
    color: w.WIRE.accent
  });
}

/** Подтабы полки. «Тактика» погашена текстом, но нарисована живой рамкой — не выключена. */
function subtabs(
  ctx: CanvasRenderingContext2D,
  width: number,
  height: number,
  at: TabsAt,
  active: number
): void {
  const labels = ["СОСУДЫ", "МЕМЕНТО", "ПРЕДМЕТЫ", "ТАКТИКА"];
  const y = at === "top" ? 0.062 : at === "under" ? 0.695 : 0.7;
  const x0 = at === "top" ? 0.33 : 0.03;
  labels.forEach((t, i) => {
    w.box(ctx, { x: x0 + i * 0.095, y, w: 0.09, h: 0.036 }, width, height, {
      label: t,
      size: 7,
      lit: i === active
    });
  });
  // Погашенная вкладка объявляет себя вслух: молчащая серая кнопка читается как поломка.
  w.text(ctx, "позже", { x: x0 + 3 * 0.095 + 0.045, y: y + 0.055 }, width, height, {
    size: 6,
    align: "center",
    color: w.WIRE.dim
  });
}

/** Карточка героя: спрайт в рост, островок земли под ногами в ракурсе арены, подпись строкой.
 *  Земля — не украшение: на неё кладутся предметы, и она же цель перетаскивания. */
function hero(
  ctx: CanvasRenderingContext2D,
  width: number,
  height: number,
  i: number,
  mode: number,
  top: number,
  bottom: number
): void {
  const x = 0.03 + i * 0.235;
  const cw = 0.22;
  const cx = x + cw / 2;
  const empty = mode === 0 && i === 3; // на вкладке «Сосуды» четвёртое место строя пустует

  // Рамка карточки — та самая фактура таро, поднятая с расходника на личность.
  w.box(ctx, { x, y: top, w: cw, h: bottom - top }, width, height, {
    hollow: true,
    lit: i === 0,
    dashed: empty
  });

  if (empty) {
    w.text(ctx, "пустое место", { x: cx, y: (top + bottom) / 2 }, width, height, {
      size: 8,
      align: "center",
      color: w.WIRE.dim
    });
    w.text(ctx, "в строю", { x: cx, y: (top + bottom) / 2 + 0.03 }, width, height, {
      size: 8,
      align: "center",
      color: w.WIRE.dim
    });
    return;
  }

  const groundY = bottom - 0.11;
  const spriteTop = top + 0.03;

  // Спрайт: почти вся высота карточки. Слотов рядом нет — Мементо читается самим обликом.
  w.box(ctx, { x: x + 0.022, y: spriteTop, w: cw - 0.044, h: groundY - spriteTop - 0.01 },
    width, height, { label: "спрайт", sub: "в полный рост", size: 7, hollow: true });

  w.ground(ctx, { x: cx, y: groundY, w: cw - 0.03 }, width, height, { lit: i === 0 });

  // Предметы стоят НА земле у ног — навесное усиление, а не часть человека.
  if (mode === 2)
    for (let s = 0; s < 4; s++) {
      const r = { x: cx - 0.058 + s * 0.031, y: groundY - 0.012, w: 0.026, h: 0.026 };
      w.box(ctx, r, width, height, { dashed: s === 3 || s >= (ITEMS[i] ?? 0) });
      if (s === 3) w.lock(ctx, r, width, height);
    }

  // Подпись одной строкой, «имя, титул». Три цвета, не два: занятый облик — акцент, свободный —
  // приглушённый, иначе пустота светится наравне с обликом.
  const relic = RELICS[i] ?? "";
  w.text(ctx, `${NAMES[i] ?? ""},`, { x: cx - 0.004, y: bottom - 0.042 }, width, height, {
    size: 9,
    align: "right"
  });
  w.text(ctx, relic === "" ? " Свободный сосуд" : ` ${relic}`,
    { x: cx - 0.004, y: bottom - 0.042 }, width, height, {
      size: 9,
      color: relic === "" ? w.WIRE.dim : w.WIRE.accent
    });

  if (mode === 0)
    w.text(ctx, "в бою", { x: cx, y: bottom - 0.016 }, width, height, {
      size: 7,
      align: "center",
      color: w.WIRE.dim
    });
}

/** Полка: то единственное, что вкладка на самом деле меняет. Иконками, а не карточками-таро. */
function shelf(
  ctx: CanvasRenderingContext2D,
  width: number,
  height: number,
  mode: number,
  tabsAt: TabsAt
): void {
  const headY = tabsAt === "shelf" ? 0.7 : 0.705;
  const top = 0.755;

  const titles = ["ЗАПАС ГИЛЬДИИ", "СКЛАД МЕМЕНТО", "СКЛАД ПРЕДМЕТОВ", "ПРОФИЛИ ПОВЕДЕНИЯ"];
  const counts = ["8 мест · 6 открыто", "12 · поиск", "12 · поиск", "закрыто"];

  if (tabsAt !== "shelf")
    w.text(ctx, titles[mode] ?? "", { x: 0.03, y: headY + 0.018 }, width, height, {
      size: 7,
      color: w.WIRE.accent
    });
  w.text(ctx, counts[mode] ?? "", { x: 0.97, y: headY + 0.018 }, width, height, {
    size: 7,
    align: "right",
    color: w.WIRE.dim
  });

  if (mode === 3) {
    w.text(ctx, "механика не продумана — полка закрыта до своего захода",
      { x: 0.37, y: 0.85 }, width, height, { size: 8, align: "center", color: w.WIRE.dim });
    return;
  }

  // Плитка квадратная и одного размера на всех полках: язык полки один, что бы на ней ни лежало.
  const cols = 12;
  const gap = 0.007;
  const areaW = 0.94;
  const cw = (areaW - gap * (cols - 1)) / cols;
  const ch = (cw * width) / height;

  for (let col = 0; col < cols; col++)
    w.box(ctx, { x: 0.03 + col * (cw + gap), y: top, w: cw, h: ch }, width, height, {
      lit: col === 0,
      dashed: mode === 0 && col > 5
    });

  w.text(ctx, "тянуть отсюда на героя", { x: 0.03, y: top + ch + 0.032 }, width, height, {
    size: 7,
    color: w.WIRE.dim
  });
}

/** Тултип по наведению — единственный дом описаний и статов.
 *
 *  Постоянной панели справа НЕТ (решение Макса 23.08.2026: «Зачем эта панель вообще? Наводимся на
 *  героев. Нам так и так тултип со статами… И так во всем»). Она занимала четверть кадра всегда,
 *  отвечая на вопрос, который задают изредка, и была вторым механизмом описаний при уже живой
 *  цепочке `TooltipChain`. Освободившаяся ширина ушла героям.
 *
 *  Это ОТМЕНЯЕТ прежнее решение того же Макса от 22.08.2026 (ГДД §0: «сравнивать по всплывающим
 *  окнам нельзя», §3: панель постоянная) — оба места в ГДД переписываются, иначе в доке останутся
 *  два взаимоисключающих правила. */
function tooltip(ctx: CanvasRenderingContext2D, width: number, height: number, mode: number): void {
  const r = { x: 0.235, y: 0.14, w: 0.2, h: 0.3 };
  w.box(ctx, r, width, height, { lit: true });

  const lines = [
    ["Ирма, Антимаг", "HP 820 · броня 24", "урон 41 · скорость 3.2", "в бою · первая в строю"],
    ["Антимаг · боевая · редкая", "гасит чужую магию", "урон +12 · броня +4", "надето: Ирма"],
    ["Сапоги · обычный", "скорость +0.4", "надет: Ирма", "тянуть обратно — снять"],
    ["Ирма, Антимаг", "профиль не назначен", "", ""]
  ];
  (lines[mode] ?? []).forEach((s2, i) => {
    if (!s2) return;
    w.text(ctx, s2, { x: r.x + 0.012, y: r.y + 0.05 + i * 0.045 }, width, height, {
      size: 7,
      color: i === 0 ? w.WIRE.accent : w.WIRE.dim
    });
  });

  w.text(ctx, "тултип по наведению", { x: r.x + r.w / 2, y: r.y + r.h - 0.03 }, width, height, {
    size: 6,
    align: "center",
    color: w.WIRE.dim
  });
}

/** Полный кадр каркаса. */
function frame(mode: number, tabsAt: TabsAt) {
  return (ctx: CanvasRenderingContext2D, width: number, height: number): void => {
    w.screen(ctx, width, height);
    topbar(ctx, width, height);
    subtabs(ctx, width, height, tabsAt, mode);

    // Карточки занимают почти всю высоту над полкой: это и был заказ «спрайт на весь экран».
    const top = tabsAt === "top" ? 0.115 : 0.075;
    const bottom = tabsAt === "under" ? 0.675 : 0.685;
    for (let i = 0; i < 4; i++) hero(ctx, width, height, i, mode, top, bottom);

    shelf(ctx, width, height, mode, tabsAt);
    tooltip(ctx, width, height, mode);
  };
}

/** Схема каркаса: что стоит намертво, а что меняет вкладка. Объяснение, не раскладка. */
