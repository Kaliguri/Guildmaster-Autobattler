const FIGHTERS = ["Ирма", "Кай", "Дан", "Лея"];

/** Строка бойца: портрет и три полосы стопкой, значение сразу за концом дорожки. */
function fighterRow(
  ctx: CanvasRenderingContext2D,
  r: w.Rect,
  width: number,
  height: number,
  name: string,
  bars: number[],
  lit = false
): void {
  if (lit) w.box(ctx, r, width, height, { lit: true });
  w.box(ctx, { x: r.x + 0.006, y: r.y + 0.012, w: 0.032, h: r.h - 0.024 }, width, height, {
    hollow: true,
    dashed: true
  });
  w.text(ctx, name, { x: r.x + 0.045, y: r.y + 0.022 }, width, height, { size: 8 });

  const trackX = r.x + 0.045;
  const trackW = r.w - 0.13;
  bars.forEach((v, i) => {
    const y = r.y + 0.042 + i * 0.026;
    w.box(ctx, { x: trackX, y, w: trackW, h: 0.018 }, width, height, { hollow: true });
    if (v > 0) w.box(ctx, { x: trackX, y, w: trackW * v, h: 0.018 }, width, height, { lit: true });
    // Значение подписано СРАЗУ ЗА КОНЦОМ ДОРОЖКИ, а не в общей колонке — так у рефа.
    w.text(ctx, [String(Math.round(v * 294)), String(Math.round(v * 40)), "0"][i]!, {
      x: trackX + trackW + 0.008,
      y: y + 0.009
    }, width, height, { size: 7, color: w.WIRE.accent });
  });
}

/* ---------- А: исход крупно, две панели в ряд (реф Guildrun) ---------- */

function drawTwoPanels(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  // Мир и размыт, и погашен — втрое темнее, чем под событием.
  w.scrim(ctx, width, height, 0.8);

  // Исход крупнее всего на экране; стоит по центру БЛОКА ПАНЕЛЕЙ, а не по центру кадра.
  w.text(ctx, "ПОБЕДА", { x: 0.48, y: 0.17 }, width, height, { align: "center", size: 20 });

  // Две панели в ряд: «итоги» 52% и «результаты» 20.2%, зазор 0.7%.
  const left: w.Rect = { x: 0.113, y: 0.228, w: 0.52, h: 0.606 };
  w.box(ctx, left, width, height, {});
  w.text(ctx, "ИТОГИ", { x: 0.133, y: 0.27 }, width, height, { size: 9, color: w.WIRE.accent });
  w.box(ctx, { x: 0.29, y: 0.285, w: 0.083, h: 0.04 }, width, height, { label: "ЖУРНАЛ", size: 7, lit: true });
  w.box(ctx, { x: 0.378, y: 0.285, w: 0.115, h: 0.04 }, width, height, { label: "КАРТОЧКИ", size: 7 });
  FIGHTERS.forEach((n, i) => {
    fighterRow(
      ctx,
      { x: 0.125, y: 0.35 + i * 0.115, w: 0.495, h: 0.105 },
      width,
      height,
      n,
      [[1, 0.08, 0], [0.6, 0.3, 0], [0.35, 0.9, 0], [0.2, 0.05, 0]][i]!,
      i === 0
    );
  });

  const right: w.Rect = { x: 0.64, y: 0.228, w: 0.202, h: 0.606 };
  w.box(ctx, right, width, height, {});
  w.text(ctx, "РЕЗУЛЬТАТЫ", { x: 0.66, y: 0.27 }, width, height, { size: 9, color: w.WIRE.accent });
  [
    ["Победа", "¤ 15"],
    ["Без потерь", "¤ 5"],
    ["Итого", "¤ 20"]
  ].forEach(([label, value], i) => {
    w.text(ctx, label!, { x: 0.66, y: 0.33 + i * 0.05 }, width, height, { size: 8, color: w.WIRE.dim });
    w.text(ctx, value!, { x: 0.822, y: 0.33 + i * 0.05 }, width, height, {
      size: 9,
      align: "right",
      color: w.WIRE.accent
    });
  });
  w.box(ctx, { x: 0.668, y: 0.726, w: 0.145, h: 0.06 }, width, height, {
    label: "ПРОДОЛЖИТЬ",
    size: 9,
    lit: true
  });
  w.callout(
    ctx,
    { x: 0.4, y: 0.4 },
    { x: 0.5, y: 0.88 },
    "полоса — вход в разбор по наведению",
    width,
    height
  );
  // Под панелью, а не над ней: сверху стоит слово исхода, самое крупное на экране.
  w.measure(ctx, left, "52%", width, height);
}

/* ---------- Б: одна панель, статистика вкладкой ---------- */

function drawOnePanel(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.8);

  w.text(ctx, "ПОБЕДА", { x: 0.5, y: 0.14 }, width, height, { align: "center", size: 20 });
  w.text(ctx, "Акт I · узел 4 · 7.2 сек", { x: 0.5, y: 0.2 }, width, height, {
    align: "center",
    size: 8,
    color: w.WIRE.dim
  });

  const panel: w.Rect = { x: 0.25, y: 0.24, w: 0.5, h: 0.58 };
  w.box(ctx, panel, width, height, {});
  // Награды и статистика — две вкладки одной панели: экран сразу отвечает «сколько дали», а разбор
  // боя лежит на второй вкладке для тех, кому интересно.
  w.box(ctx, { x: 0.27, y: 0.27, w: 0.12, h: 0.045 }, width, height, { label: "НАГРАДЫ", size: 8, lit: true });
  w.box(ctx, { x: 0.395, y: 0.27, w: 0.14, h: 0.045 }, width, height, { label: "РАЗБОР БОЯ", size: 8 });

  [
    ["Победа", "¤ 15"],
    ["Без потерь", "¤ 5"],
    ["Реликвия", "Щит заставы"],
    ["Итого", "¤ 20"]
  ].forEach(([label, value], i) => {
    w.text(ctx, label!, { x: 0.28, y: 0.36 + i * 0.06 }, width, height, { size: 9, color: w.WIRE.dim });
    w.text(ctx, value!, { x: 0.72, y: 0.36 + i * 0.06 }, width, height, {
      size: 10,
      align: "right",
      color: w.WIRE.accent
    });
  });

  w.box(ctx, { x: 0.6, y: 0.73, w: 0.13, h: 0.06 }, width, height, { label: "Дальше", size: 9, lit: true });
  w.measure(ctx, panel, "50%", width, height);
}

/* ---------- В: без панели, всё лентой поверх поля боя ---------- */

function drawBanner(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.5);

  // Панели нет: поле боя остаётся видимым, итоги ложатся лентой поперёк кадра.
  w.box(ctx, { x: 0, y: 0.32, w: 1, h: 0.28 }, width, height, {});
  w.text(ctx, "ПОБЕДА", { x: 0.5, y: 0.42 }, width, height, { align: "center", size: 20 });
  w.text(ctx, "¤ 20   ·   Щит заставы   ·   7.2 сек", { x: 0.5, y: 0.51 }, width, height, {
    align: "center",
    size: 10,
    color: w.WIRE.accent
  });

  w.box(ctx, { x: 0.44, y: 0.66, w: 0.12, h: 0.06 }, width, height, { label: "Дальше", size: 9, lit: true });
  w.box(ctx, { x: 0.58, y: 0.66, w: 0.14, h: 0.06 }, width, height, { label: "Разбор боя", size: 9 });
  w.callout(
    ctx,
    { x: 0.65, y: 0.72 },
    { x: 0.6, y: 0.82 },
    "статистика — по кнопке, а не сразу",
    width,
    height,
    "right"
  );
  w.measure(ctx, { x: 0, y: 0.32, w: 1, h: 0.28 }, "100% ширины", width, height);
}

