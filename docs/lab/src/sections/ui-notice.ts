/* Сообщения игроку: одна модель — два облика.

   Разбор 20.08.2026. До него всё, что игра хотела сказать, показывалось одинаково — модалкой по
   центру: и «нельзя надеть реликвию, нет слота», и «связь оборвалась, что делаем». Первое не должно
   останавливать игру вовсе, второе обязано её остановить.

   Ось разделения — НЕ важность (её каждый заказчик оценит по-своему), а есть ли у сообщения вопрос
   к игроку. Признак уже лежит в модели `NoticeRequest`: список ответов. Пустой — говорить не о чем,
   значит лента; непустой — игра ждёт решения, значит модалка со scrim. */

