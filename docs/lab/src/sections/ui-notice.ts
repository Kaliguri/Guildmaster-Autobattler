/** Карта углов кадра: кто где живёт, чтобы четыре ленты не подрались за один угол. */
function drawCorners(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);

  w.box(ctx, { x: 0.02, y: 0.06, w: 0.22, h: 0.20 }, width, height,
    { label: "игроки", sub: "кто с нами", size: 11 });
  w.box(ctx, { x: 0.62, y: 0.50, w: 0.36, h: 0.14 }, width, height,
    { label: "лента", sub: "снизу справа, над журналом", lit: true, size: 11 });
  w.box(ctx, { x: 0.62, y: 0.66, w: 0.36, h: 0.26 }, width, height,
    { label: "журнал событий", sub: "тает снизу вверх", size: 11 });
  w.box(ctx, { x: 0.02, y: 0.74, w: 0.30, h: 0.18 }, width, height,
    { label: "чат", sub: "Enter · Esc", size: 11 });

  w.callout(ctx, { x: 0.62, y: 0.57 }, { x: 0.44, y: 0.57 },
    "выше всех слоёв, кликов не берёт", width, height, "right");
}

/** Модалка: ярлык вида выступает над кромкой панели, ответы внизу. */
function drawModal(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height);

  const panel: w.Rect = { x: 0.30, y: 0.30, w: 0.40, h: 0.40 };
  w.box(ctx, panel, width, height, {});
  w.box(ctx, { x: 0.38, y: 0.255, w: 0.24, h: 0.06 }, width, height,
    { label: "НЕ ПОЛУЧИЛОСЬ", lit: true, size: 10 });

  w.text(ctx, "Связь с хозяином потеряна.", { x: 0.50, y: 0.46 }, width, height,
    { align: "center", size: 11 });
  w.text(ctx, "Забег останется у него.", { x: 0.50, y: 0.51 }, width, height,
    { align: "center", size: 10, color: w.WIRE.dim });

  w.box(ctx, { x: 0.325, y: 0.60, w: 0.11, h: 0.055 }, width, height, { label: "Ждать", size: 9 });
  w.box(ctx, { x: 0.445, y: 0.60, w: 0.11, h: 0.055 }, width, height, { label: "В меню", size: 9 });
  w.box(ctx, { x: 0.565, y: 0.60, w: 0.11, h: 0.055 }, width, height,
    { label: "Выйти", lit: true, size: 9 });

  w.measure(ctx, panel, "40% x 40%", width, height);
}

/** Лента: строки в правом нижнем углу над журналом, живут временем. */
function drawToast(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);

  // Журнал на своём месте — лента приходит ровно над ним и на время его подпирает.
  w.box(ctx, { x: 0.62, y: 0.70, w: 0.36, h: 0.22 }, width, height,
    { hollow: true, dashed: true, label: "журнал", size: 9 });

  const strip: w.Rect = { x: 0.62, y: 0.545, w: 0.36, h: 0.07 };
  w.box(ctx, strip, width, height, {});
  w.text(ctx, "Нет свободного слота под реликвию", { x: 0.64, y: 0.58 }, width, height, { size: 10 });

  w.box(ctx, { x: 0.62, y: 0.625, w: 0.36, h: 0.07 }, width, height, {});
  w.text(ctx, "Гилберт присоединился", { x: 0.64, y: 0.66 }, width, height,
    { size: 10, color: w.WIRE.dim });

  w.callout(ctx, { x: 0.62, y: 0.58 }, { x: 0.44, y: 0.58 }, "3 c, потом тает", width, height, "right");
  w.callout(ctx, { x: 0.62, y: 0.66 }, { x: 0.44, y: 0.66 }, "не больше трёх зараз", width, height, "right");
  w.measure(ctx, strip, "36% x 7%", width, height);
}

/** Как было до разбора: модалка на всё подряд. */
function drawBefore(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height);

  w.box(ctx, { x: 0.30, y: 0.30, w: 0.40, h: 0.40 }, width, height, {});
  w.text(ctx, "Нет свободного слота", { x: 0.50, y: 0.44 }, width, height,
    { align: "center", size: 11 });
  w.box(ctx, { x: 0.565, y: 0.60, w: 0.11, h: 0.055 }, width, height,
    { label: "Понятно", lit: true, size: 9 });
  w.callout(ctx, { x: 0.50, y: 0.70 }, { x: 0.50, y: 0.80 },
    "игра встала ради того, о чём не спрашивают", width, height, "center");
}

