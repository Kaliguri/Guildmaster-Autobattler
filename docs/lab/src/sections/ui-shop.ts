/** Товар: рамка, иконка, имя, строки статов, цена пилюлей у нижней кромки. */
function goods(
  ctx: CanvasRenderingContext2D,
  r: w.Rect,
  width: number,
  height: number,
  opts: { lit?: boolean; price?: string; rows?: number; locked?: boolean } = {}
): void {
  w.box(ctx, r, width, height, { lit: opts.lit });
  // Иконка в левом верхнем углу — у Brotato всего 2.4% площади карточки, минимум среди рефов.
  w.box(ctx, { x: r.x + 0.008, y: r.y + 0.015, w: 0.028, h: 0.05 }, width, height, {
    hollow: true,
    dashed: true
  });
  w.text(ctx, "Название", { x: r.x + 0.042, y: r.y + 0.04 }, width, height, { size: 9 });
  w.text(ctx, "тип словом", { x: r.x + 0.042, y: r.y + 0.068 }, width, height, {
    size: 7,
    color: w.WIRE.dim
  });
  const rows = opts.rows ?? 5;
  for (let i = 0; i < rows; i++) {
    w.text(
      ctx,
      "стат: новое | старое",
      { x: r.x + 0.012, y: r.y + 0.11 + i * 0.032 },
      width,
      height,
      { size: 7, color: w.WIRE.dim }
    );
  }
  // Цена — пилюля по центру нижней кромки; у выбранного товара она инвертируется.
  w.box(
    ctx,
    { x: r.x + r.w / 2 - 0.029, y: r.y + r.h - 0.062, w: 0.058, h: 0.046 },
    width,
    height,
    { label: opts.price ?? "27 ¤", size: 11, lit: opts.lit }
  );
  if (opts.locked) {
    // «Lock» стоит СНАРУЖИ карточки, под ней — так у Brotato, по одной кнопке на слот.
    w.box(ctx, { x: r.x + r.w / 2 - 0.016, y: r.y + r.h + 0.012, w: 0.032, h: 0.04 }, width, height, {
      label: "фикс",
      size: 7
    });
  }
}

/* ---------- А: ряд товаров и панель статов справа (реф Brotato) ---------- */

function drawRowStats(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.scrim(ctx, width, height, 0.75);

  // Кошелёк вверху по центру, без плашки — так у рефа.
  w.text(ctx, "¤ 210", { x: 0.5, y: 0.07 }, width, height, { align: "center", size: 13 });
  // Реролл с ЦЕНОЙ ПРЯМО НА КНОПКЕ — приём, снимающий вопрос «а сколько это стоит».
  w.box(ctx, { x: 0.79, y: 0.045, w: 0.16, h: 0.055 }, width, height, {
    label: "ОБНОВИТЬ — 7 ¤",
    size: 8
  });

  // Четыре товара 18.4% x 44.6%, зазор 0.8%, прижаты к левому краю.
  for (let i = 0; i < 4; i++) {
    goods(ctx, { x: 0.01 + i * 0.192, y: 0.16, w: 0.184, h: 0.446 }, width, height, {
      lit: i === 1,
      price: ["35 ¤", "72 ¤", "27 ¤", "27 ¤"][i],
      locked: true
    });
  }

  // Панель статов справа 22% x 65%: ненулевые окрашены, нулевые серые.
  const stats: w.Rect = { x: 0.775, y: 0.16, w: 0.215, h: 0.65 };
  w.box(ctx, stats, width, height, { hollow: true });
  w.text(ctx, "СТАТЫ ОТРЯДА", { x: 0.79, y: 0.2 }, width, height, { size: 9 });
  for (let i = 0; i < 8; i++) {
    w.text(ctx, "стат", { x: 0.79, y: 0.245 + i * 0.055 }, width, height, { size: 7, color: w.WIRE.dim });
    w.text(ctx, i % 3 === 0 ? "+12" : "0", { x: 0.978, y: 0.245 + i * 0.055 }, width, height, {
      size: 8,
      align: "right",
      color: i % 3 === 0 ? w.WIRE.accent : w.WIRE.dim
    });
  }

  w.box(ctx, { x: 0.8, y: 0.86, w: 0.16, h: 0.06 }, width, height, { label: "Дальше", lit: true, size: 9 });
  w.measure(ctx, { x: 0.01, y: 0.16, w: 0.184, h: 0.446 }, "18.4%", width, height, "x", "before");
}

/* ---------- Б: сетка карт и отдельная группа мелких товаров (реф STS2) ---------- */

function drawGrid(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.scrim(ctx, width, height, 0.75);

  w.text(ctx, "ЛАВКА", { x: 0.5, y: 0.07 }, width, height, { align: "center", size: 12 });
  w.text(ctx, "¤ 210", { x: 0.95, y: 0.07 }, width, height, { align: "right", size: 11 });

  // Карточка 10.4% x 25% — самая мелкая среди рефов; сетка 5 + 2, зазор 3.2%.
  const cw = 0.104;
  const gap = 0.032;
  for (let i = 0; i < 5; i++) {
    const x = 0.06 + i * (cw + gap);
    w.box(ctx, { x, y: 0.17, w: cw, h: 0.25 }, width, height, { lit: i === 0 });
    // Цена стоит СНАРУЖИ карточки, под ней — так у рефа.
    w.text(ctx, "¤ 75", { x: x + cw / 2, y: 0.45 }, width, height, { align: "center", size: 9 });
  }
  for (let i = 0; i < 2; i++) {
    const x = 0.06 + i * (cw + gap);
    w.box(ctx, { x, y: 0.52, w: cw, h: 0.25 }, width, height, {});
    w.text(ctx, "¤ 150", { x: x + cw / 2, y: 0.8 }, width, height, { align: "center", size: 9 });
  }

  // Мелкие товары отдельной группой справа: реликвии и расходники живут не в общей сетке.
  w.text(ctx, "РЕЛИКВИИ И ЗЕЛЬЯ", { x: 0.62, y: 0.55 }, width, height, { size: 8, color: w.WIRE.dim });
  for (let i = 0; i < 6; i++) {
    w.box(
      ctx,
      { x: 0.62 + (i % 3) * 0.07, y: 0.58 + Math.floor(i / 3) * 0.11, w: 0.055, h: 0.09 },
      width,
      height,
      {}
    );
  }
  // Услуга — не товар: у рефа это отдельная кнопка «удалить карту».
  w.box(ctx, { x: 0.84, y: 0.58, w: 0.11, h: 0.2 }, width, height, {
    label: "услуга",
    sub: "снять реликвию",
    size: 8
  });

  w.box(ctx, { x: 0.05, y: 0.87, w: 0.12, h: 0.055 }, width, height, { label: "Назад", size: 9 });
  w.measure(ctx, { x: 0.06, y: 0.17, w: cw, h: 0.25 }, "10.4%", width, height, "x", "before");
}

/* ---------- В: полка и продажа снизу (то, что в игре) ---------- */

function drawShelf(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.scrim(ctx, width, height, 0.7);

  const panel: w.Rect = { x: 0.14, y: 0.1, w: 0.72, h: 0.8 };
  w.box(ctx, panel, width, height, {});
  w.text(ctx, "ЛАВКА", { x: 0.5, y: 0.15 }, width, height, { align: "center", size: 12 });

  w.text(ctx, "Золото: 210", { x: 0.17, y: 0.22 }, width, height, { size: 10 });
  w.box(ctx, { x: 0.7, y: 0.195, w: 0.14, h: 0.05 }, width, height, { label: "Обновить", size: 8 });

  for (let i = 0; i < 4; i++) {
    goods(ctx, { x: 0.17 + i * 0.17, y: 0.28, w: 0.155, h: 0.33 }, width, height, {
      lit: i === 0,
      rows: 3,
      price: "27 ¤"
    });
  }

  // Продажа — отдельной секцией внизу той же панели. Ни один реф так не делает: у Brotato владения
  // показаны без цен, у STS2 продажи нет вовсе.
  w.text(ctx, "ПРОДАТЬ РЕЛИКВИИ", { x: 0.17, y: 0.68 }, width, height, { size: 8, color: w.WIRE.accent });
  for (let i = 0; i < 5; i++) {
    w.box(ctx, { x: 0.17 + i * 0.075, y: 0.71, w: 0.06, h: 0.1 }, width, height, {});
  }
  w.callout(
    ctx,
    { x: 0.55, y: 0.76 },
    { x: 0.66, y: 0.8 },
    "продажи нет ни у одного рефа класса",
    width,
    height
  );

  w.box(ctx, { x: 0.72, y: 0.83, w: 0.12, h: 0.05 }, width, height, { label: "Дальше", lit: true, size: 8 });
  w.measure(ctx, panel, "72%", width, height, "x", "before");
}

