/* Экран события: три раскладки.

   Источник — `Art_Dev/UI Refs/_teardowns/05-event-map-outcome.md` §1, два рефа: Guildrun и
   Slay the Spire 2. Они противоположны в главном — в том, ЧТО обещает плашка выбора:

     · Guildrun пишет только КАТЕГОРИЮ («КРИСТАЛЛЫ» + «Выбрать стартовый набор кристаллов») —
       ни чисел, ни валют, ни цвета риска;
     · STS2 пишет ПОСЛЕДСТВИЯ числами прямо в плашке и красит их по смыслу: «Gain 143 Gold.
       Lose 18 HP.» — приобретение синим, потеря красным, название ресурса золотым.

   Это и есть развилка события: сюрприз против информированного решения. Раскладка идёт следом.

   Что в игре сейчас: `EventScreen.uxml` — панель по центру, иллюстрация сверху, тело, плашки. */

import * as w from "./ui-wire.js";
import type { SectionDef } from "../types.js";

/** Плашка варианта: заголовок и строка последствий. */
function choice(
  ctx: CanvasRenderingContext2D,
  r: w.Rect,
  width: number,
  height: number,
  title: string,
  outcome: string | null,
  lit = false
): void {
  w.box(ctx, r, width, height, { lit });
  // Левый торец утолщён — единственная асимметрия формы у Guildrun, акцентная планка.
  w.box(ctx, { x: r.x, y: r.y, w: 0.004, h: r.h }, width, height, { lit: true });
  w.text(ctx, title, { x: r.x + 0.016, y: r.y + (outcome ? r.h * 0.32 : r.h / 2) }, width, height, {
    size: 9
  });
  if (outcome) {
    w.text(ctx, outcome, { x: r.x + 0.016, y: r.y + r.h * 0.7 }, width, height, {
      size: 8,
      color: w.WIRE.accent
    });
  }
}

/* ---------- А: панель справа, арт слева и заходит под неё (реф Guildrun) ---------- */

function drawArtOverlap(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  // Мир НЕ гасят — его расфокусируют: у рефа детализация падает в 60 раз, а светлота остаётся.
  w.scrim(ctx, width, height, 0.25);

  // Панель 41.9% x 61.9%, кайма только на трёх сторонах: слева она обрывается в арт.
  const panel: w.Rect = { x: 0.456, y: 0.167, w: 0.419, h: 0.619 };
  w.box(ctx, panel, width, height, {});

  // Арт 45.7% x 77% заходит внутрь панели на 6.6% ширины экрана и прорывает её нижнюю кайму.
  w.box(ctx, { x: 0.066, y: 0.118, w: 0.457, h: 0.77 }, width, height, {
    hollow: true,
    dashed: true,
    label: "иллюстрация",
    size: 9
  });

  w.text(ctx, "СТАРТОВЫЙ НАБОР", { x: 0.476, y: 0.229 }, width, height, { size: 11 });
  for (let i = 0; i < 3; i++) {
    w.text(ctx, "строка текста события", { x: 0.476, y: 0.28 + i * 0.032 }, width, height, {
      size: 8,
      color: w.WIRE.dim
    });
  }
  // Плашки 31.9% x 7.9%, шаг 9.3%. Последствий на них нет — только категория.
  ["КРИСТАЛЛЫ", "СЛИТКИ", "СВИТКИ"].forEach((t, i) => {
    choice(ctx, { x: 0.475, y: 0.42 + i * 0.093, w: 0.319, h: 0.079 }, width, height, t, null, i === 0);
  });
  w.callout(
    ctx,
    { x: 0.52, y: 0.62 },
    { x: 0.45, y: 0.72 },
    "правая колонка и низ панели пустые",
    width,
    height,
    "right"
  );
  w.measure(ctx, panel, "41.9%", width, height, "x", "before");
}

/* ---------- Б: панели нет, текст на угасающей сцене (реф STS2) ---------- */

function drawNoPanel(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  // Слева сцена, справа она сама угасает в чёрный — роль панели играет угол кадра.
  const grad = ctx.createLinearGradient(0, 0, width, 0);
  grad.addColorStop(0, "rgba(30,0,38,0.15)");
  grad.addColorStop(0.5, "rgba(8,8,10,0.75)");
  grad.addColorStop(1, "rgba(4,4,5,0.95)");
  w.worldBehind(ctx, width, height);
  ctx.fillStyle = grad;
  ctx.fillRect(0, 0, width, height);

  w.box(ctx, { x: 0.04, y: 0.2, w: 0.4, h: 0.62 }, width, height, {
    hollow: true,
    dashed: true,
    label: "сцена, а не иллюстрация",
    size: 8
  });

  w.text(ctx, "Лабиринт джунглей", { x: 0.69, y: 0.241 }, width, height, { align: "center", size: 11 });
  // Тело и плашки РОВНО одной ширины (41.3%) и по одной оси — от этого блок читается как колонка.
  for (let i = 0; i < 5; i++) {
    w.text(ctx, "строка текста события", { x: 0.486, y: 0.3 + i * 0.038 }, width, height, {
      size: 8,
      color: w.WIRE.dim
    });
  }
  choice(
    ctx,
    { x: 0.486, y: 0.55, w: 0.413, h: 0.09 },
    width,
    height,
    "Одиночный поход",
    "+143 золота · −18 HP",
    true
  );
  choice(ctx, { x: 0.486, y: 0.66, w: 0.413, h: 0.09 }, width, height, "Уйти", "+51 золота");
  w.callout(
    ctx,
    { x: 0.9, y: 0.65 },
    { x: 0.95, y: 0.79 },
    "последствия числами в плашке",
    width,
    height,
    "right"
  );
  w.measure(ctx, { x: 0.486, y: 0.55, w: 0.413, h: 0.09 }, "41.3%", width, height, "x", "before");
}

/* ---------- В: панель по центру, иллюстрация сверху (то, что в игре) ---------- */

function drawCenterPanel(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.6);

  const panel: w.Rect = { x: 0.28, y: 0.1, w: 0.44, h: 0.8 };
  w.box(ctx, panel, width, height, {});
  w.text(ctx, "СОБЫТИЕ", { x: 0.5, y: 0.15 }, width, height, { align: "center", size: 11 });

  w.box(ctx, { x: 0.31, y: 0.19, w: 0.38, h: 0.22 }, width, height, {
    hollow: true,
    dashed: true,
    label: "иллюстрация",
    size: 8
  });
  for (let i = 0; i < 4; i++) {
    w.text(ctx, "строка текста события", { x: 0.31, y: 0.45 + i * 0.034 }, width, height, {
      size: 8,
      color: w.WIRE.dim
    });
  }
  ["Помочь", "Пройти мимо", "Обыскать"].forEach((t, i) => {
    choice(ctx, { x: 0.31, y: 0.6 + i * 0.085, w: 0.38, h: 0.07 }, width, height, t, null, i === 0);
  });
  w.measure(ctx, panel, "44%", width, height, "x", "before");
}

