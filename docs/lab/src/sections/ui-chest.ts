/* Экран сундука: три раскладки.

   ЧЕСТНАЯ ОГОВОРКА, с которой раздел начинается: рефа этого класса у нас НЕТ. В базе из семи
   разобранных классов сундук не встречается ни разу — ни в `04-reward-shop-choice`, ни в
   `05-event-map-outcome`. Поэтому здесь не «так делают N из M», а перенос приёмов из соседних
   классов плюс один вопрос, на который придётся ответить самим: чем сундук отличается от награды.

   Механически он от неё почти не отличается: и там, и там игрок получает содержимое узла карты.
   Разница только в жесте — сундук СНАЧАЛА закрыт, и открытие это отдельный момент. Если жест
   ничего не добавляет, экран сундука не нужен вовсе, и это третий вариант ниже.

   Что в игре сейчас: `ChestScreen.uxml` — крышка с глифом и подсказкой «Нажми, чтобы открыть». */

import * as w from "../lib/ui-wire.js";
import type { SectionDef } from "../types.js";

/* ---------- А: жест открытия, затем ряд карточек ---------- */

function drawTwoBeats(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.6);

  // Левая половина кадра — такт первый: закрытый сундук.
  ctx.strokeStyle = w.WIRE.line;
  ctx.setLineDash([3, 3]);
  ctx.beginPath();
  ctx.moveTo(0.5 * width, 0.08 * height);
  ctx.lineTo(0.5 * width, 0.92 * height);
  ctx.stroke();
  ctx.setLineDash([]);

  w.text(ctx, "ТАКТ 1 — закрыт", { x: 0.25, y: 0.14 }, width, height, {
    align: "center",
    size: 9,
    color: w.WIRE.accent
  });
  w.box(ctx, { x: 0.16, y: 0.32, w: 0.18, h: 0.24 }, width, height, { label: "◆", size: 22, lit: true });
  w.text(ctx, "нажми, чтобы открыть", { x: 0.25, y: 0.62 }, width, height, {
    align: "center",
    size: 8,
    color: w.WIRE.dim
  });

  w.text(ctx, "ТАКТ 2 — содержимое", { x: 0.75, y: 0.14 }, width, height, {
    align: "center",
    size: 9,
    color: w.WIRE.accent
  });
  // Такт второй — ОБЫЧНЫЙ экран награды, тот самый вариант Б: лежачие строки. Своей раскладки у
  // содержимого сундука нет, и это часть решения Макса: «сначала просто сундук, анимка и обычный
  // ревард экран».
  for (let i = 0; i < 3; i++) {
    const r: w.Rect = { x: 0.535, y: 0.26 + i * 0.145, w: 0.43, h: 0.135 };
    w.box(ctx, r, width, height, { lit: i === 0 });
    w.box(ctx, { x: r.x + 0.006, y: r.y + 0.016, w: 0.042, h: 0.104 }, width, height, {
      hollow: true,
      dashed: true,
      label: "◆",
      size: 10
    });
    w.text(ctx, "название", { x: 0.59, y: r.y + 0.04 }, width, height, { size: 9 });
    w.text(ctx, ["обычная", "редкая", "обычная"][i]!, { x: r.x + r.w - 0.01, y: r.y + 0.04 }, width, height, {
      size: 7,
      align: "right",
      color: i === 1 ? w.WIRE.accent : w.WIRE.dim
    });
    w.text(ctx, "описание эффекта", { x: 0.59, y: r.y + 0.078 }, width, height, {
      size: 7,
      color: w.WIRE.dim
    });
    w.text(ctx, "‣ Урон: 50 ➜ 60", { x: 0.59, y: r.y + 0.11 }, width, height, {
      size: 7,
      color: w.WIRE.accent
    });
  }
  w.measure(ctx, { x: 0.535, y: 0.26, w: 0.43, h: 0.135 }, "60% экрана награды", width, height, "x", "before");
}

/* ---------- Б: сундук раскрывается на месте, содержимое вокруг него ---------- */

function drawBurst(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.55);

  w.text(ctx, "СУНДУК", { x: 0.5, y: 0.1 }, width, height, { align: "center", size: 12 });

  // Сундук остаётся на экране и после открытия: он якорь композиции, содержимое встаёт вокруг.
  w.box(ctx, { x: 0.42, y: 0.38, w: 0.16, h: 0.22 }, width, height, { label: "◆", size: 20, lit: true });

  const around: Array<[number, number]> = [
    [0.24, 0.24],
    [0.62, 0.24],
    [0.24, 0.62],
    [0.62, 0.62]
  ];
  around.forEach(([x, y], i) => {
    w.box(ctx, { x, y, w: 0.14, h: 0.16 }, width, height, { lit: i === 0 });
    w.text(ctx, "предмет", { x: x + 0.07, y: y + 0.08 }, width, height, {
      align: "center",
      size: 8,
      color: w.WIRE.dim
    });
  });
  w.callout(
    ctx,
    { x: 0.5, y: 0.62 },
    { x: 0.53, y: 0.74 },
    "сундук не исчезает: он держит центр композиции",
    width,
    height
  );

  w.box(ctx, { x: 0.42, y: 0.84, w: 0.16, h: 0.06 }, width, height, { label: "Забрать всё", lit: true, size: 9 });
  w.measure(ctx, { x: 0.42, y: 0.38, w: 0.16, h: 0.22 }, "16%", width, height, "x", "before");
}

/* ---------- В: своего экрана нет — содержимое приходит наградой ---------- */

function drawNoScreen(ctx: CanvasRenderingContext2D, width: number, height: number): void {
  w.screen(ctx, width, height);
  w.worldBehind(ctx, width, height);
  w.scrim(ctx, width, height, 0.5);

  w.text(ctx, "НАГРАДА", { x: 0.5, y: 0.085 }, width, height, { align: "center", size: 12 });
  w.text(ctx, "из сундука", { x: 0.5, y: 0.125 }, width, height, {
    align: "center",
    size: 8,
    color: w.WIRE.accent
  });

  // Тот же экран награды, только заголовок называет источник. Отдельного экрана сундука нет.
  const cw = 0.181;
  const gap = 0.028;
  const left = (1 - (cw * 3 + gap * 2)) / 2;
  for (let i = 0; i < 3; i++) {
    const x = left + i * (cw + gap);
    w.box(ctx, { x, y: 0.2, w: cw, h: 0.55 }, width, height, { lit: i === 1 });
    w.box(ctx, { x: x + 0.008, y: 0.22, w: cw - 0.016, h: 0.17 }, width, height, {
      hollow: true,
      dashed: true,
      label: "арт",
      size: 8
    });
    w.text(ctx, "НАЗВАНИЕ", { x: x + cw / 2, y: 0.42 }, width, height, { align: "center", size: 9 });
    for (let k = 0; k < 3; k++) {
      w.text(ctx, "описание", { x: x + 0.012, y: 0.47 + k * 0.033 }, width, height, {
        size: 7,
        color: w.WIRE.dim
      });
    }
  }
  w.callout(
    ctx,
    { x: 0.5, y: 0.78 },
    { x: 0.56, y: 0.87 },
    "экран сундука не заводится: узел карты называет источник",
    width,
    height
  );
  w.measure(ctx, { x: left, y: 0.2, w: cw, h: 0.55 }, "18.1%", width, height, "x", "before");
}

