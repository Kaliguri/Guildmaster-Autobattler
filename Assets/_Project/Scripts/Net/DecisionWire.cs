namespace Guildmaster.Net
{
    /// <summary>
    /// Кто говорит на канале общего решения. Первый байт сообщения.
    /// </summary>
    /// <remarks>
    /// <b>Тег вместо разбора по длине.</b> Раньше стороны различались тем, что голос гостя занимал ровно
    /// один байт, а объявление хоста было длиннее. Держалось это до первого изменения формата — и
    /// сломалось на нём: голос стал строкой варианта (07.08.2026), длины сравнялись, и хост принял бы
    /// собственное эхо за чужой голос. Признак отправителя обязан быть в сообщении, а не в его размере.
    /// </remarks>
    public static class DecisionWire
    {
        /// <summary>Голос участника: гость → хост.</summary>
        public const byte Vote = 0;

        /// <summary>Объявленный счёт с поимённым списком голосов: хост → всем.</summary>
        public const byte Tally = 1;
    }
}
