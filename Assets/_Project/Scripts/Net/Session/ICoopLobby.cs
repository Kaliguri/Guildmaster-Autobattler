using System;

namespace Guildmaster.Net.Session
{
    /// <summary>
    /// Откуда берутся напарники: комната, приглашение и ответ на чужое приглашение.
    /// </summary>
    /// <remarks>
    /// <b>Шов заведён 05.08.2026 ради проверяемости, а не ради вторых реализаций в игре.</b> Вход к
    /// другу у нас один — приглашение платформы (решение Макса 02.08.2026: входа по адресу нет и не
    /// будет). Из-за этого гостевая половина сеанса не отыгрывалась нигде, кроме живого прогона
    /// вдвоём: программно «принять приглашение» было нечем, а значит разрыв, реконнект и приём
    /// приглашения из разных мест игры проверялись только руками.
    /// <para>Игроку шов ничего не добавляет: кнопок больше не стало, дорога к напарнику по-прежнему
    /// одна.</para>
    /// </remarks>
    public interface ICoopLobby
    {
        /// <summary>Готова ли платформа: без неё звать некого и некуда.</summary>
        bool IsSteamReady { get; }

        /// <summary>Поднята ли комната — только тогда есть куда приглашать.</summary>
        bool HasLobby { get; }

        /// <summary>Нас позвали: комната и адрес хозяина.</summary>
        event Action<ulong, ulong> JoinRequested;

        /// <summary>Комната изменилась — состав, состояние, что угодно видимое экрану.</summary>
        event Action LobbyChanged;

        void CreateLobby();
        void OpenInviteOverlay();
        void OpenFriendsOverlay();
        void LeaveLobby();
    }
}
