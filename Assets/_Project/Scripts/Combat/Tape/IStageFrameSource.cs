using System.Collections.Generic;

namespace Guildmaster.Combat.Tape
{
    /// <summary>
    /// Кто поставляет показу кадр сцены: кто стоит на арене, где и в какой позе.
    /// </summary>
    /// <remarks>
    /// <b>Шов существует, потому что поставщиков двое.</b> В бою кадр приходит с ленты — с лагом
    /// показа, интерполяцией и снарядами. Вне боя (двор гильдии, Ристалище, ростер между забегами)
    /// боевой симуляции не существует вовсе, а тела на арене стоять обязаны: их держит свой мировой
    /// слой. Показ разницы не видит — он и раньше рисовал только кадр, а живая симуляция была нужна
    /// ему лишь для dev-оверлеев.
    /// <para><b>Почему это вообще возможно</b> — решение Макса 02.08.2026 «симуляция принадлежит бою»:
    /// <c>CombatSimulation</c> рождается и умирает вместе с боем, и вечного владельца тел больше нет.
    /// Разбор — журнал <c>2026-08-02-the-simulation-belongs-to-the-battle-and-the-world-holds-bodies</c>.</para>
    /// </remarks>
    public interface IStageFrameSource
    {
        /// <summary>
        /// Продвинуть момент показа на прошедшее время. Зовётся ровно раз за кадр — владелец момента
        /// один, иначе разные потребители увидели бы разное «сейчас».
        /// </summary>
        void Advance(float deltaTime);

        /// <summary>
        /// Доля кадра сверх показанного тика: из неё показ интерполирует движение между снимками.
        /// У статичной сцены смысла не имеет и постоянна.
        /// </summary>
        float Alpha { get; }

        /// <summary>
        /// Кадр целиком. <c>false</c> — показывать пока нечего (лента пуста, арена пуста).
        /// </summary>
        bool TryGetFrame(out IReadOnlyList<UnitSnapshot> units, out IReadOnlyList<ProjectileSnapshot> projectiles);
    }
}
