using UnityEngine;

namespace Guildmaster.Combat
{
    /// <summary>
    /// Куда встают призванные тела относительно хозяина. ЕДИНСТВЕННЫЙ владелец раскладки: её просят и
    /// способность призыва (<see cref="AbilitySystem"/>), и стартовый отряд
    /// (<c>SummonOnBattleStartComponent</c>), а две копии одной формулы разъезжаются на первой же правке.
    /// </summary>
    /// <remarks>
    /// <para><b>Раскладка обязана быть ЗЕРКАЛЬНОЙ, а не одинаковой</b> — на этом и погорела прежняя
    /// редакция. Она считала смещение чисто от индекса, без запросов к миру, и делала из этого вывод, что
    /// у обеих команд оно совпадает. Совпадать ему как раз нельзя: у отражённых сторон противоположен X,
    /// поэтому единственное смещение (а у обоих призывателей ростера призыв ровно один) уводило тело
    /// левого за спину, а тело правого — вперёд, между хозяином и врагом. Дальше расходилось всё:
    /// дистанция, выбор цели, расталкивание.</para>
    /// <para>Отсюда оси: <b>назад — вдоль тыла команды</b> (<see cref="FleeSteering.HomeDir"/>, он же
    /// владелец конвенции сторон), <b>веер — поперёк фронта</b>. X меняет знак вместе с командой, Y у
    /// отражённых сторон совпадает — ровно то, что требует зеркало.</para>
    /// </remarks>
    public static class SummonLayout
    {
        /// <summary>Смещение тела от призывателя: назад на пол-шага, веером поперёк фронта.</summary>
        /// <param name="index">Порядковый номер тела в этом призыве, с нуля.</param>
        /// <param name="step">Шаг раскладки — размер призывателя: крупный хозяин не рождает тела внутри себя.</param>
        /// <param name="summoner">Хозяин; из него берётся сторона команды, и только она.</param>
        public static Vector2 Offset(int index, float step, RuntimeUnit summoner)
        {
            int lane = (index / 2) + 1;                   // пары расходятся от оси всё дальше
            float across = (index % 2 == 0) ? -1f : 1f;   // чётные — в одну сторону фронта, нечётные — в другую
            return FleeSteering.HomeDir(summoner) * (step * 0.5f)
                   + new Vector2(0f, across * step * lane);
        }
    }
}
