using Guildmaster.Data.Definitions;
using UnityEngine;

namespace Guildmaster.Combat
{
    /// <summary>
    /// Шов «собрать юнита посреди боя» (M10). Симуляция умеет ставить тела на поле
    /// (<c>EnqueueUnitSpawn</c>), но собирать их из SO не умеет и знать об этом не должна — сборка живёт
    /// в <see cref="RuntimeUnitFactory"/>, снаружи боевого ядра.
    /// <para><b>Почему отдельный интерфейс, а не ссылка на фабрику:</b> симуляции нужен ровно один метод
    /// из неё, и только для призывов. Узкий шов заодно оставляет бою возможность работать без фабрики —
    /// так живут балансные бенчи, где состав задан заранее и призывать некого.</para>
    /// <para><b>Составом арены владеет расстановка</b>, и призыв — сознательное исключение из этого
    /// правила: он не «заказывает состав мимо расстановки», а является боевой механикой, чьи тела
    /// появляются по ходу боя и в нём же гибнут.</para>
    /// </summary>
    public interface ISummonFactory
    {
        /// <summary>
        /// Собрать призванного юнита. Статы берутся из <paramref name="data"/> и множатся на
        /// <c>SummonHealthEff</c> / <c>SummonDamageEff</c> призывателя — так «усилить призывы» становится
        /// одной ручкой предмета, а не правкой каждого ассета призыва.
        /// </summary>
        /// <param name="data">Кит призванного юнита — единственный источник его базовых чисел.</param>
        /// <param name="team">Команда призывателя.</param>
        /// <param name="position">Куда поставить тело.</param>
        /// <param name="summoner">Кто призвал: его множители применяются, он же владелец связи.</param>
        RuntimeUnit CreateSummon(UnitData data, int team, Vector2 position, RuntimeUnit summoner);
    }
}
