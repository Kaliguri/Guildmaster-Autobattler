namespace Guildmaster.Combat
{
    /// <summary>
    /// Фаза боевого действия юнита — единый источник истины для «занятости» авто-атакой (вики «14»).
    /// Владелец перехода — <see cref="AutoAttackSystem"/>; движение/презентация/способности только читают.
    /// Детерминизм: фаза выводится из int-счётчиков тиков (<see cref="RuntimeUnit.WindupRemaining"/>,
    /// <see cref="RuntimeUnit.RecoveryRemaining"/>), а не из времени.
    /// </summary>
    public enum AttackPhase
    {
        /// <summary>
        /// <b>Вне боя:</b> юнит в цикл атаки не вошёл. Цель может быть уже выбрана, но он до неё не
        /// достаёт — бежит, стоит без цели, лежит в стане. Движется на полной скорости.
        /// </summary>
        /// <remarks>
        /// Пара к <see cref="CombatIdle"/> (решение Макса 2026-07-30/10). Прежний <c>Idle</c> описывал две
        /// несовместимые ситуации разом — «не дерётся вовсе» и «дерётся, но сейчас между ударами», — и
        /// пока свинг занимал весь интервал, разницы не было. С окном между атаками она принципиальна:
        /// парированию нужно знать, кто именно на него нацелен, а бегущий мимо не то же самое, что ждущий
        /// своего удара боец.
        /// </remarks>
        Idle = 0,

        /// <summary>Замах до кадра контакта: юнит «занят» (рут либо штраф скорости при стрельбе на ходу), урон в конце.</summary>
        Windup = 1,

        /// <summary>Хвост-восстановление после удара: всё ещё «занят», новый замах начать нельзя, пока не истечёт.</summary>
        Recovery = 2,

        /// <summary>
        /// Канал авто-атаки: удар не одномоментный, а поток тиков урона между замахом и хвостом
        /// (<see cref="RuntimeUnit.ChannelRemaining"/>). Юнит «занят» так же, как в замахе.
        /// </summary>
        /// <remarks>
        /// Фаза, а не отдельный ритм (решение Макса 2026-07-30). Канал встаёт МЕЖДУ замахом и хвостом —
        /// «долгий занос → поток → долгое сворачивание», — поэтому прерывание контролем, рут движения,
        /// показ и будущее парирование продолжают работать по одному закону для всех ударов. Ритм рядом с
        /// двухфазным потребовал бы второй копии каждого из этих правил.
        /// <para>Тик канала — это обычный удар: урон <c>AutoAttackDamage</c>, интервал между тиками
        /// <c>1 / AttackSpeed</c>. Отсюда DPS канала равен классовой норме кита и считается той же формулой,
        /// что у всех; цена канала — замах и хвост, в которые он не бьёт вовсе.</para>
        /// </remarks>
        Channel = 3,

        /// <summary>
        /// <b>Боевое ожидание:</b> удар отработан, следующий ещё не начался — юнит стоит в цикле атаки и
        /// держит цель в досягаемости, дожидаясь своего интервала.
        /// </summary>
        /// <remarks>
        /// Четвёртое состояние цикла атаки (решение Макса 2026-07-30/10). В «состояние атаки» НЕ входит:
        /// удар не идёт, прерывать нечего. Но цель известна и держится, и из этого растут три следствия:
        /// <list type="bullet">
        /// <item>юнит движется на <b>полной</b> скорости — штраф «стрельбы на ходу» живёт только на трёх
        /// фазах удара, и это ровно то окно, в котором цель успевает убежать от стрелка (07-30/13);</item>
        /// <item>он <b>держит слот боевого контакта и линию</b> — иначе танк между ударами формально
        /// отпускал бы фронт и слоты перетасовывались бы каждый цикл (07-30/14);</item>
        /// <item>его <b>ловит парирование</b>: он выбрал парирующего целью авто-атаки, хотя замах ещё не
        /// занёс (07-30/12).</item>
        /// </list>
        /// <para>Отличие от <see cref="Idle"/> — в досягаемости, а не в наличии цели: бегущий к цели ещё
        /// не в бою. Значение <b>дописано в конец</b>: порядок существующих не менять, он уезжает в снимок
        /// показа.</para>
        /// </remarks>
        CombatIdle = 4,
    }
}
