using System;

namespace Guildmaster.Combat.Effects.Components
{
    /// <summary>
    /// <b>Окно парирования</b> (дизайн Макса 2026-07-30, триггер уточнён 2026-07-31): пока эффект висит,
    /// носитель отменяет входящие удары ближнего боя целиком. Длительность окна живёт в
    /// <c>_baseDuration</c> самого эффекта (0.3 с у общего ассета) — своего поля у компонента нет
    /// намеренно: окно и есть эффект, второе число рассинхронизировалось бы с первым.
    /// </summary>
    /// <remarks>
    /// <b>Почему окно — отдельный эффект, а не таймер внутри <see cref="ParryComponent"/>:</b> парирование
    /// срабатывает по прилетевшему удару и гасит его тут же, а дальше защита обязана жить сама — её
    /// видит показ, её снимает диспел, её длительность крутится в ассете. Таймер внутри компонента был бы
    /// состоянием, о котором не знает никто снаружи.
    /// <para><b>Гасит ВСЕ удары окна, а не один</b> (вердикт Макса 2026-07-31, против дефолта скрайба).
    /// Прямое следствие, принятое сознательно: против парирующего многоударная Атака теряет столько
    /// Ударов, сколько уместилось в 0.3 с, — то есть парирование сильнее всего именно против серий.</para>
    /// <para><b>Дееспособности НЕ требует</b>, в отличие от <see cref="ParryComponent"/>: окно уже
    /// открыто. Стан, прилетевший в парирующего после открытия, отнимает у него ответную атаку — этого
    /// достаточно, и отнимать заодно уже поднятый клинок значило бы наказать дважды за одно попадание.</para>
    /// </remarks>
    [Serializable]
    public sealed class ParryWindowComponent : IPreDamageComponent
    {
        public void OnApply(in EffectContext ctx) { }

        public void OnExpire(in EffectContext ctx) { }

        public void OnPreDamage(in DamageRequest incoming, PreDamageResult result, in EffectContext ctx)
        {
            if (result.Negated) return;
            if (!ParryComponent.IsParryable(in incoming)) return;

            result.Negated = true;
        }
    }
}
