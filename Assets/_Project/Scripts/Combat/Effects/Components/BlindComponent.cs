using System;
using UnityEngine;

namespace Guildmaster.Combat.Effects.Components
{
    /// <summary>
    /// <b>Слепота</b> (ГДД, каталог эффектов §Детерминизм): ослеплённый бьёт, но часть его атак уходит
    /// мимо — <b>каждая X-я</b>, а не «с шансом». Глубина задаётся стаками: один стак промахивает одну
    /// атаку из четырёх, четыре стака — все четыре из четырёх.
    /// <para><b>Числа:</b> <c>_periodAtOneStack</c> — из скольких атак промахивается одна при ОДНОМ стаке
    /// (4 = каждая четвёртая). Каждый следующий стак сокращает период на единицу, до одной атаки: при
    /// четырёх стаках слепой не попадает вовсе. Больше ничего здесь нет намеренно — «насколько слепой»
    /// решают стаки источника, а не своё поле у каждого носителя.</para>
    /// <para><b>Когда срабатывает:</b> на снятии цифр авто-атаки носителя, по его счётчику Ударов
    /// (<see cref="RuntimeUnit.HitsMade"/>).</para>
    /// </summary>
    /// <remarks>
    /// <b>Стаки копятся порциями, как кровотечение</b> (решение Макса 2026-07-31): каждое наложение живёт
    /// свой срок и сходит отдельно, поэтому слепота ослабевает постепенно — с четырёх промахов из четырёх
    /// до одного из четырёх, — а не гаснет разом. Отсюда и потолок в четыре: пятый стак было бы нечем
    /// выразить, кроме «мимо чаще, чем бьёт».
    /// <para><b>Счёт по ударам ЮНИТА, а не по счётчику эффекта:</b> порций несколько, и у каждой свой
    /// <c>Counter</c> — период считался бы от разных начал, и «каждая четвёртая» превратилась бы в
    /// «когда как». Контра слепоте — Меткость из того же каталога, и она обязана считать тот же счётчик.</para>
    /// <para><b>Дееспособности не требует:</b> слепота не отнимает волю — оглушённый и ослеплённый мешают
    /// по-разному, и складываться они должны без взаимного гашения.</para>
    /// </remarks>
    [Serializable]
    public sealed class BlindComponent : IAttackMissComponent, IStackableComponent
    {
        [Tooltip("Из скольких атак промахивается одна при ОДНОМ стаке (4 = каждая четвёртая). " +
                 "Каждый следующий стак сокращает период на 1, минимум — каждая атака.")]
        [Min(1)]
        [SerializeField] private int _periodAtOneStack = 4;

        public void OnApply(in EffectContext ctx) { }

        public void OnExpire(in EffectContext ctx) { }

        public void OnStacksChanged(int previousStacks, in EffectContext ctx)
        {
            // Стаки читаются в момент удара, состояния между ударами компонент не держит — значит и
            // рестак ничего не пересчитывает. Дефолтный OnExpire→OnApply здесь тоже был бы безвреден,
            // но пустой метод честнее: он говорит, что глубина слепоты выводится, а не хранится.
        }

        public bool MissesAttack(RuntimeUnit attacker, in EffectContext ctx)
        {
            if (attacker == null) return false;

            int stacks = Depth(in ctx);
            int period = _periodAtOneStack - (stacks - 1);
            if (period < 1) period = 1;

            // Считаем по УЖЕ нанесённым Ударам: счётчик инкрементируется до опроса, поэтому первый
            // удар под слепотой — это HitsMade == 1, и при периоде 4 мимо уходит четвёртый.
            // Удары, а не Атаки: слепота гасит отдельный контакт, и у многоударного кита их в Атаке
            // несколько. Открытый долг — «каждая X-я АТАКА мимо» из ГДД: перевод на счётчик Атак у
            // канального кита отправил бы мимо весь поток разом (open-forks, ритм атаки, п. 2).
            return attacker.HitsMade % period == 0;
        }

        /// <summary>
        /// Глубина слепоты — сколько наложений на носителе. У порционной модели читается числом порций
        /// (<see cref="RuntimeEffect.VisibleStacks"/> синхронизирован с ним), у остальных — обычными стаками.
        /// </summary>
        /// <remarks>
        /// <c>EffectContext.Stacks</c> для порций намеренно отдаёт 1: там вклад всех порций уже сложен в
        /// потенцию, и множить его ещё и числом порций значило бы посчитать их дважды. У слепоты вклад не в
        /// цифрах — глубину она берёт из счёта порций, и это не обход правила, а другой вопрос к тем же
        /// данным. Снимок на начало тика соблюдается: <c>VisibleStacks</c> отдаёт именно его.
        /// </remarks>
        private static int Depth(in EffectContext ctx)
        {
            RuntimeEffect eff = ctx.Effect;
            if (eff?.Def != null && eff.Def.Stacking == Data.Definitions.StackRule.Portions)
                return eff.VisibleStacks < 1 ? 1 : eff.VisibleStacks;

            return ctx.Stacks < 1 ? 1 : ctx.Stacks;
        }
    }
}
