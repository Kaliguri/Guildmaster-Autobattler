namespace Guildmaster.Combat.Effects
{
    /// <summary>
    /// Стартовые приоритеты pre-damage реакций: чем больше число, тем раньше реакцию спросят
    /// (решение Макса 2026-08-21/3). Опрос идёт по убыванию и обрывается на первой, отменившей удар, —
    /// значит порядок решает, чей ресурс сгорит, а чей уцелеет.
    /// <para><b>Ступени названы по тому, насколько рано реакция вмешивается в событие:</b> уход убирает
    /// цель из-под удара, отбив встречает удар зарядом, поглощение съедает то, что долетело, множитель
    /// только меняет число. Отсюда и порядок — «сначала уходишь, потом отбиваешь, потом терпишь».</para>
    /// <para><b>Это дефолты, а не закон.</b> Числа стоят здесь одним списком, чтобы их было видно
    /// вместе; компонент вправе взять своё значение между ступенями. Настройку приоритета игроком через
    /// AI-профиль закладывали как шов (<see cref="Guildmaster.Data.Definitions.AIProfile"/> сегодня несёт
    /// один <c>PassiveTrigger</c> на весь юнит, списка по эффектам в нём нет).</para>
    /// </summary>
    public static class ReactionPriority
    {
        /// <summary>Уход: цель покидает место удара — «Отход», фазовый сдвиг, сдвиг союзника ветром.</summary>
        public const int Evade = 300;

        /// <summary>Отбив: удар встречают зарядом — парирование, «Оплот».</summary>
        public const int Deflect = 200;

        /// <summary>Поглощение: съесть долетевшее — щиты по школе и по дальности, резисты.</summary>
        public const int Absorb = 100;

        /// <summary>Множитель: только меняет число урона — «Угли», уязвимости.</summary>
        public const int Modify = 0;
    }

    /// <summary>
    /// Тай-брейк при равных <see cref="ReactionPriority"/>: чья это реакция (решение Макса 2026-08-21/3).
    /// Меньше значение — раньше спросят.
    /// <para><b>Почему своё раньше чужого:</b> собственный заряд восстанавливается сам и дёшев, а реакция
    /// союзника — редкий ресурс на всю команду. Сжечь чужую поддержку на удар, который боец пережил бы
    /// своим отходом, расточительно.</para>
    /// <para><b>Ступени «от предмета» здесь нет намеренно.</b> Предметы сегодня дают только статы
    /// (<c>EffectiveStats.Build</c>) и ни одной реакции не вешают — признака «эффект пришёл из предмета» в
    /// <see cref="RuntimeEffect"/> не существует. Заводить ступень под несуществующего носителя значит
    /// выдумать поле, которое некому заполнять; место под неё — между <see cref="SelfCast"/> и
    /// <see cref="FromAlly"/>.</para>
    /// </summary>
    public enum ReactionOrigin
    {
        /// <summary>Эффект наложен самим носителем (или у него нет источника) — своя реакция.</summary>
        SelfCast = 0,

        /// <summary>Эффект наложен другим юнитом — чужая реакция на носителе.</summary>
        FromAlly = 2,
    }
}
