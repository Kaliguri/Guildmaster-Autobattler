using System;
using Guildmaster.Core.Persistence;

namespace Guildmaster.Core.Settings
{
    /// <summary>
    /// Какие каналы диагностики включены на ЭТОЙ машине.
    /// </summary>
    /// <remarks>
    /// <b>Хранится рядом с настройками экрана, в машинно-локальном файле, и это не мелочь.</b> Выбор
    /// каналов — свойство отладочного сеанса конкретного компьютера, а не игрока: облачная
    /// синхронизация растащила бы его по машинам, где он бессмыслен.
    /// <para><b>Зачем вообще хранить.</b> Кооп разбирается двумя людьми на двух машинах, и включать
    /// каналы приходится ОБОИМ и каждый запуск. Забыл один — прогон бесполезен наполовину: ровно так
    /// и вышло 05.08.2026, когда команду ввели вручную и переиграли заход.</para>
    /// </remarks>
    [Serializable]
    [SaveSchema(1)]
    public sealed class DiagSettings
    {
        /// <summary>
        /// Набор каналов числом — тем же, что и в <c>DiagChannel</c>. Именно числом, а не списком имён:
        /// имена каналов меняются при рефакторинге, и сохранённый выбор пережил бы переименование
        /// молча, включив не то.
        /// </summary>
        public int Channels;
    }
}
