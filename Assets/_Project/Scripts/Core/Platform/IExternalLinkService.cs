namespace Guildmaster.Core.Platform
{
    /// <summary>
    /// Дверь наружу: открыть веб-страницу или страницу игры в магазине.
    /// </summary>
    /// <remarks>
    /// <b>Интерфейс здесь, реализация в сетевом слое</b> — потому что открывает ссылку по-хорошему
    /// оверлей Steam, а знание про Steam живёт там же, где рукопожатие и лобби. UI обязан уметь
    /// позвать «открой», не зная, чем именно это кончится: в оверлее, в браузере или ничем.
    /// <para><b>Ответа нет намеренно.</b> Ни один из способов не сообщает, дошёл ли игрок до
    /// страницы, — а значит и врать про успех нечем. Единственное, что можно спросить заранее, —
    /// <see cref="OverlayAvailable"/>: по нему экран решает, показывать ли то, что без Steam не
    /// имеет смысла.</para>
    /// </remarks>
    public interface IExternalLinkService
    {
        /// <summary>Есть ли оверлей Steam — то есть запущена ли игра через клиент.</summary>
        bool OverlayAvailable { get; }

        /// <summary>Открыть произвольный адрес. Пустая строка — ничего не делаем.</summary>
        void OpenUrl(string url);

        /// <summary>
        /// Открыть страницу игры в магазине — то место, где игрок жмёт «В список желаемого».
        /// </summary>
        /// <remarks>
        /// Отдельным методом, а не адресом среди прочих: в оверлее у страницы магазина свой вызов,
        /// и он открывается прямо поверх игры, тогда как тот же адрес через <see cref="OpenUrl"/>
        /// увёл бы во встроенный браузер оверлея — там нет ни кнопки желаемого, ни цены.
        /// <para>Добавить в желаемое ЗА игрока нельзя: Steam такого API не даёт вовсе — ни
        /// Steamworks SDK, ни веб-API. Максимум, что нам позволено, — привести на страницу.</para>
        /// </remarks>
        void OpenStorePage();
    }
}
