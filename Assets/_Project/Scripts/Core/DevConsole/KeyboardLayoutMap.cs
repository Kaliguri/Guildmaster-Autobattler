namespace Guildmaster.Core.DevConsole
{
    /// <summary>
    /// Перевод набранного в русской раскладке в латиницу по ПОЗИЦИИ клавиши: <c>ушщ_ыуз</c> →
    /// <c>gis_sep</c>. Нужен консоли, где все имена команд латинские: переключать раскладку ОС игра не
    /// может, а требовать этого от разработчика — терять секунду на каждом вызове.
    /// </summary>
    /// <remarks>
    /// <b>Позиционный маппинг, а не транслитерация.</b> Человек не «пишет по-русски» — он жмёт клавишу
    /// <c>G</c>, а система рисует «п». Значит правильный ответ — вернуть символ, который дала бы та же
    /// клавиша в английской раскладке, а не фонетический аналог буквы (<c>п</c> → <c>p</c> было бы
    /// «правильно» по звуку и неправильно по клавише).
    /// <para><b>Переводится ВСЁ, включая содержимое кавычек</b> (решение Макса 31.07: «в консоль всегда
    /// автоматом пишем на англ раскладке»). Предсказуемое правило дороже гибкости: консоль набирают на
    /// автомате, и «здесь переводит, а внутри кавычек нет» пришлось бы держать в голове. Понадобится
    /// русский текст аргументом — исключение для кавычек добавляется здесь одной проверкой.</para>
    /// </remarks>
    public static class KeyboardLayoutMap
    {
        // Индексы совпадают: одна клавиша — одна пара. Раскладка ЙЦУКЕН (Windows, стандартная).
        //
        // ВАЖНО: сами '.' и ',' в таблице НЕ участвуют, хотя позиционно они соответствуют '/' и '?'.
        // Иначе «0.35» превращалось бы в «0/35» — точка нужна консоли как десятичный разделитель, и
        // это ловил тест Layout_LatinAndDigitsPassThrough. Кириллические 'ю' и 'б' по-прежнему дают
        // '.' и ',': перевод идёт только В латиницу, латинские символы неприкосновенны.
        private const string Cyrillic = "йцукенгшщзхъфывапролджэячсмитьбюёЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮЁ";
        private const string Latin    = "qwertyuiop[]asdfghjkl;'zxcvbnm,.`QWERTYUIOP{}ASDFGHJKL:\"ZXCVBNM<>~";

        /// <summary>
        /// Заменить кириллические символы на латинские по позиции клавиши. Символы, которых в раскладке
        /// нет (цифры, пробел, уже латинские буквы), проходят как есть.
        /// </summary>
        public static string ToLatin(string value)
        {
            if (string.IsNullOrEmpty(value)) return value;

            char[] buffer = null;

            for (int i = 0; i < value.Length; i++)
            {
                int at = Cyrillic.IndexOf(value[i]);
                if (at < 0) continue;

                // Массив создаём только если что-то реально меняется: ввод латиницей — обычный случай,
                // и платить за него копией строки на каждый символ незачем.
                if (buffer == null) buffer = value.ToCharArray();
                buffer[i] = Latin[at];
            }

            return buffer == null ? value : new string(buffer);
        }
    }
}
