namespace Guildmaster.Core.Simulation
{
    /// <summary>
    /// Остаток тикового аккумулятора, выраженный долей шага симуляции. Симуляция идёт фиксированными
    /// шагами <see cref="SimConstants.TickDelta"/>, а рендер — с частотой монитора: между двумя тиками
    /// умещается ноль, один или несколько кадров, и каждый из них должен рисовать позицию не «на тике»,
    /// а там, где тело было бы в этот момент.
    /// <para>Владелец величины ровно один — тот, кто копит время (боевая петля). Презентация только
    /// читает: собственный подсчёт доли по <c>Time.deltaTime</c> даёт не долю шага, а отношение
    /// длительности кадра к тику — при стабильном fps это константа, то есть вечная середина между
    /// двумя тиками вместо движения.</para>
    /// </summary>
    public interface ISimInterpolation
    {
        /// <summary>Доля шага, прошедшая с последнего тика, в диапазоне [0, 1].</summary>
        float Alpha { get; }
    }
}
