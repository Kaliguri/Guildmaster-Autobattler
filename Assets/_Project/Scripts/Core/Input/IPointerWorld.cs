using UnityEngine;

namespace Guildmaster.Core.Input
{
    /// <summary>
    /// Где указатель игрока в мировых координатах.
    /// </summary>
    /// <remarks>
    /// <b>Свой шов, потому что владельцев перевода «экран → мир» стало двое.</b> Расстановка считала его
    /// сама, присутствие считало бы второй раз — и чужой курсор поехал бы относительно того, что игрок
    /// на самом деле трогает, стоило бы одному из двух забыть про смещение камеры по глубине.
    /// <para><b>Мир, а не экран,</b> потому что курсор едет по сети: у игроков разные разрешения и разный
    /// вид камеры, и пиксель у одного не значит ничего у другого. В мировых координатах он указывает на
    /// того же бойца.</para>
    /// </remarks>
    public interface IPointerWorld
    {
        /// <summary>Положение указателя в мире. Без камеры отвечает нулём — рисовать всё равно негде.</summary>
        Vector2 Position { get; }

        /// <summary>Есть ли камера, то есть значит ли <see cref="Position"/> хоть что-то.</summary>
        bool IsAvailable { get; }
    }
}
