namespace Guildmaster.Core.Input
{
    /// <summary>
    /// Игровой контекст ввода — определяет, какие карты действий активны в данный момент
    /// (вики «16» §2). Меняется по макро-фазе игры; переключение делает <see cref="IInputService"/>.
    /// Пауза здесь НЕ отдельный контекст — это состояние симуляции, а действие «пауза/продолжить»
    /// живёт в боевой карте и работает в обоих состояниях.
    /// </summary>
    public enum InputContext
    {
        /// <summary>Ничего не активно (загрузка, переход между сценами).</summary>
        None = 0,

        /// <summary>Меню/оверлеи: только UI-навигация.</summary>
        Menu = 1,

        /// <summary>Фаза расстановки: камера + размещение юнитов (реализация — будущая фаза).</summary>
        Deployment = 2,

        /// <summary>Идёт бой: камера + боевые действия (пауза, рестарт).</summary>
        Combat = 3,
    }
}
