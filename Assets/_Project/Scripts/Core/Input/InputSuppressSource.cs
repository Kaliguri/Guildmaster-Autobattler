namespace Guildmaster.Core.Input
{
    /// <summary>
    /// Кто держит глушение геймплейного ввода (<see cref="IInputService.SetSuppressed"/>). Источники
    /// независимы и накапливаются: ввод оживает, когда отпустили все.
    /// <para>Флаги, а не булево на весь сервис: причина «клавиатуру забрал кто-то другой» бывает у
    /// нескольких хозяев одновременно, и с одним общим флагом они затирали друг друга. Живой случай:
    /// dev-консоль открыта (глушение стоит) → команда меняет экран → навигатор пересчитывает своё
    /// глушение и снимает ЧУЖОЕ → Enter, которым отправили команду, доходит до расстановки и
    /// начинает бой.</para>
    /// </summary>
    [System.Flags]
    public enum InputSuppressSource
    {
        /// <summary>Никто не глушит.</summary>
        None = 0,

        /// <summary>Модальный экран интерфейса (навигатор: всё, что не Sheet).</summary>
        Ui = 1 << 0,

        /// <summary>Dev-консоль QFSW: пока она открыта, клавиатура принадлежит ей.</summary>
        DevConsole = 1 << 1,
    }
}
