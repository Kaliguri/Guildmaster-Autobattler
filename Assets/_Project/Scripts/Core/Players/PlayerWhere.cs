namespace Guildmaster.Core.Players
{
    /// <summary>
    /// Где игрок находится прямо сейчас: строка списка участников отвечает на самый частый вопрос
    /// кооп-вечера — «ты где?».
    /// </summary>
    /// <remarks>
    /// <b>Заказ Макса 07.08.2026</b> и принятое решение кооп-канона: носитель постоянного состояния —
    /// список игроков со значком, а не только анимация уходящего курсора
    /// (<c>gdd/50-modes-ux/coop/presence</c> §Куда ушёл игрок). Анимация — это момент, заметный лишь
    /// тому, кто в ту секунду смотрел; список отвечает в любую.
    /// <para><b>«Отошёл» — не место, а его отсутствие,</b> и стоит отдельно от переходов между
    /// экранами: свернувшего окно нельзя показывать «на карте», иначе к нему будут обращаться и ждать
    /// ответа. Требование записано там же.</para>
    /// <para><b>Значения только ДОПИСЫВАЮТСЯ:</b> номер едет по проводу, и переставленный показал бы
    /// напарника не там, где он есть, — молча, потому что обе стороны собираются порознь.</para>
    /// </remarks>
    public enum PlayerWhere : byte
    {
        /// <summary>Неизвестно: участник только вошёл и ещё не сказал о себе.</summary>
        Unknown = 0,

        /// <summary>Отошёл: окно свёрнуто или потеряло фокус. Не место, а его отсутствие.</summary>
        Away = 1,

        /// <summary>Меню игры: главное меню, выбор дома, профиль.</summary>
        Menu = 2,

        /// <summary>Двор гильдии.</summary>
        Courtyard = 3,

        /// <summary>Карта акта: выбирает путь.</summary>
        Map = 4,

        /// <summary>Боевая арена: расстановка или бой.</summary>
        Arena = 5,

        /// <summary>Снаряжение: инвентарь и лоадаут поверх любого места.</summary>
        Loadout = 6,

        /// <summary>Системное меню по Esc — поверх игры, но игрок в неё сейчас не смотрит.</summary>
        Pause = 7,
    }
}
