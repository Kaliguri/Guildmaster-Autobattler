namespace Guildmaster.Core.Players
{
    /// <summary>
    /// За какую команду играет ЭТОТ клиент. Единственный источник ответа на вопрос «мы победили?»:
    /// в бою есть команды (0, 1, …), а не «сторона игрока», поэтому исход боя сравнивается с
    /// <see cref="Team"/>, а не с захардкоженной командой.
    /// <para>Соло: одна команда на локального игрока (по умолчанию первая). Кооп: все игроки-союзники
    /// делят одну команду. PvP: у клиентов разные <see cref="Team"/> — и один и тот же исход боя для
    /// одного победа, для другого поражение.</para>
    /// </summary>
    public interface ILocalPlayer
    {
        /// <summary>Номер команды локального игрока.</summary>
        int Team { get; }
    }
}
