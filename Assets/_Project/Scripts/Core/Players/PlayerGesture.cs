namespace Guildmaster.Core.Players
{
    /// <summary>
    /// Что игрок показывает жестом. Жест ничего не сообщает механике — только людям за столом.
    /// </summary>
    /// <remarks>
    /// <b>Живёт в Core, а не рядом с присутствием,</b> хотя едет именно им: жест показывает ввод,
    /// рисует интерфейс, а возит сеть — то есть его знают три слоя, и общий у них только Core. Положи
    /// его в сетевой слой, и на него сослался бы весь проект ради одного перечисления.
    /// <para><b>Значения только ДОПИСЫВАЮТСЯ:</b> номер едет по проводу, и переставленный показал бы
    /// чужой жест вместо нужного. Словарь эмоций растёт за мелочь Гильдмастера (кооп-канон §Эмоции),
    /// на старте открыт единственный — «лайк» (решение Макса 30.07.2026).</para>
    /// </remarks>
    public enum PlayerGesture : byte
    {
        /// <summary>Ничего не показываем.</summary>
        None = 0,

        /// <summary>Лайк — первая и пока единственная доступная эмоция.</summary>
        Like = 1,

        /// <summary>
        /// Чокнуться: жест, который невозможно сделать в одиночку. Звенит, когда двое стукнулись
        /// курсорами одновременно.
        /// </summary>
        Clink = 2,
    }
}
