using System.Collections.Generic;

namespace Guildmaster.Core.Players
{
    /// <summary>
    /// Участник сеанса: кто он, за какую сторону играет и каким цветом подписан.
    /// </summary>
    /// <remarks>
    /// <b>Цвет едет ИНДЕКСОМ, а не значением.</b> Единственный владелец цвета в проекте — палитра;
    /// сеанс раздаёт места в наборе игровых цветов, а какого они оттенка, решает палитра при отрисовке.
    /// Положи мы сюда <c>Color</c> — у цвета появился бы второй владелец, живущий по сети.
    /// </remarks>
    public readonly struct SessionPlayer
    {
        /// <summary>Номер участника в сеансе — он же номер пира у транспорта.</summary>
        public readonly int Id;

        /// <summary>Как его зовут: подпись у курсора и строка в списке участников.</summary>
        public readonly string Name;

        /// <summary>За какую сторону играет. В кампании у всех одна, в PvP — разные.</summary>
        public readonly int Team;

        /// <summary>Место в наборе игровых цветов; сам цвет берётся из палитры по этому номеру.</summary>
        public readonly int ColorIndex;

        /// <summary>
        /// Скин курсора (<c>cursor.*</c>), которым игрок виден остальным. Пусто — умолчание набора.
        /// </summary>
        /// <remarks>
        /// Едет вместе с составом, потому что курсор — главное, что видят другие: скин, невидимый
        /// напарникам, перестаёт быть косметикой и становится настройкой для себя одного.
        /// </remarks>
        public readonly string CursorSkinId;

        /// <summary>
        /// Где он сейчас — значок в списке участников. Едет составом, а не присутствием: присутствие
        /// ненадёжно и шлётся по движению курсора, а стоящий в меню игрок курсором не двигает, и
        /// последнее известное место осталось бы врать.
        /// </summary>
        public readonly PlayerWhere Where;

        public SessionPlayer(int id, string name, int team, int colorIndex, string cursorSkinId = null,
                             PlayerWhere where = PlayerWhere.Unknown)
        {
            Id           = id;
            Name         = name;
            Team         = team;
            ColorIndex   = colorIndex;
            CursorSkinId = cursorSkinId ?? string.Empty;
            Where        = where;
        }

        public override string ToString() => $"#{Id} {Name} (сторона {Team}, цвет {ColorIndex}, {Where})";
    }

    /// <summary>
    /// Кто в сеансе и за какую сторону играет — единственный источник правды об этом.
    /// </summary>
    /// <remarks>
    /// <b>Заведён 03.08.2026, потому что источника не было вовсе.</b> «Своя команда» жила литеральным
    /// нулём в расстановке, и пока за игру садился один человек, ноль был верен по совпадению. При двух
    /// живых игроках в PvP обе стороны считали бы себя командой 0 и распоряжались бы одним строем.
    /// <para><b>Дом — сеанс, а не мероприятие.</b> Режим выбирается на входе в игру и внутри сеанса не
    /// меняется: в кампании я всегда за одну сторону, в PvP-матче — за свою до конца матча. Мероприятия
    /// же сменяют друг друга по ходу забега (карта, лавка, бой), и стороны, живущие в них, пришлось бы
    /// назначать заново на каждом узле.</para>
    /// <para><b><see cref="ILocalPlayer"/> — производная отсюда, а не второе мнение.</b> «Моя команда»
    /// это моя строка в этой таблице; спрашивать их врозь значило бы завести два ответа на один вопрос.</para>
    /// </remarks>
    public interface ISessionRoster
    {
        /// <summary>Все участники сеанса, включая нас. Вне сеанса — пусто.</summary>
        IReadOnlyList<SessionPlayer> Players { get; }

        /// <summary>Наш номер в сеансе.</summary>
        int LocalId { get; }

        /// <summary>Найти участника по номеру.</summary>
        bool TryGet(int playerId, out SessionPlayer player);

        /// <summary>
        /// Играет ли этот участник за нашу сторону. Главный вопрос присутствия: чужой курсор виден
        /// только своим (ГДД, кооп-кластер, presence §Кто чью сторону видит).
        /// </summary>
        bool SharesTeamWithLocal(int playerId);

        /// <summary>
        /// Разводить ли участников по разным сторонам (<c>true</c>) или посадить всех на одну.
        /// Заказывает мероприятие — оно одно знает, кому принадлежит вторая сторона арены. Исполняет
        /// хост: у гостя вызов не делает ничего, стороны ему приезжают таблицей.
        /// </summary>
        /// <remarks>
        /// Спрашивается «делить ли», а не «сколько сторон», и это не косметика. Сторон у арены всегда
        /// две; число здесь было пересказом чужого факта, и пересказ разъехался с оригиналом ровно
        /// один раз — когда кампании понадобилось запретить трогать врагов, а участники от этого
        /// разъехались по разным сторонам (07.08.2026).
        /// </remarks>
        void SplitBetweenSides(bool split);
    }
}
