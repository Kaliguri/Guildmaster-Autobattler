namespace Guildmaster.Core.Players
{
    /// <summary>
    /// Набор мейн-цветов игроков: сколько их и как назвать оттенок по выбору игрока.
    /// </summary>
    /// <remarks>
    /// <b>Один владелец числа.</b> До 22.08.2026 «сколько цветов» было записано пятью разными местами:
    /// константой экрана профиля и четырьмя выражениями <c>% 4</c> — у курсора, у списка участников, у
    /// кружков голоса и у расстановки. Расширение набора при такой раскладке чинится в пяти файлах, и
    /// каждый забытый молча укладывает половину игроков в первые четыре оттенка.
    /// <para><b>Шестнадцать, а не четыре</b> (заказ Макса 22.08.2026: «надо добавить больше цветов
    /// (около 12-16). Обычный белый в т.ч. можно взять»). Цвет при этом остаётся ПРЕДПОЧТИТЕЛЬНЫМ:
    /// в одной сессии оттенки уникальны (ГДД coop/presence), и занятый заменяется ближайшим свободным.
    /// Широкий набор ровно для того и нужен — при четырёх оттенках на четверых замена всегда была
    /// «последним, что осталось».</para>
    /// <para><b>Оттенки живут в палитре</b> (<c>--gm-color-player-N</c>), здесь только их счёт и адрес:
    /// цвет остаётся с одним владельцем, даже когда едет по сети.</para>
    /// </remarks>
    public static class PlayerColors
    {
        /// <summary>Сколько оттенков в наборе.</summary>
        public const int Count = 16;

        /// <summary>
        /// Место в наборе (1..<see cref="Count"/>) для выбора игрока. Индекс приходит по сети и из
        /// сейва, то есть снаружи, — поэтому заворачивается, а не проверяется: игрок без цвета
        /// остаться не может.
        /// </summary>
        public static int SlotOf(int colorIndex) => ((colorIndex % Count) + Count) % Count + 1;

        /// <summary>Имя токена палитры для этого выбора.</summary>
        public static string TokenOf(int colorIndex) => "--gm-color-player-" + SlotOf(colorIndex);

        /// <summary>Суффикс USS-класса (<c>p1</c>…<c>p16</c>) для семейств <c>gm-cursor--p*</c> и родни.</summary>
        public static string SuffixOf(int colorIndex) => "p" + SlotOf(colorIndex);
    }
}
