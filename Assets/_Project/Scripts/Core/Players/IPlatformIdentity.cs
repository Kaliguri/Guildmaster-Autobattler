namespace Guildmaster.Core.Players
{
    /// <summary>
    /// Как игрока зовёт платформа (Steam). Один вход в чужую личность на весь проект.
    /// </summary>
    /// <remarks>
    /// Шов существует ради слоёв: имя нужно интерфейсу (подпись «Брать имя из Steam» показывает, какое
    /// именно), а знать про Steamworks интерфейсу нельзя. Заодно это единственное место, где решается,
    /// что показывать, когда платформы нет.
    /// </remarks>
    public interface IPlatformIdentity
    {
        /// <summary>Имя игрока в платформе. Платформа недоступна — безымянное «Игрок».</summary>
        string PlayerName { get; }
    }

    /// <summary>
    /// Смена скина курсора. Узкий шов вместо доступа к сервису: интерфейсу нужно ровно одно действие —
    /// «надень вот этот», чтобы игрок увидел выбор сразу, а не после перезахода.
    /// </summary>
    public interface ICursorSkinControl
    {
        /// <summary>
        /// Надеть скин по id, покрасив его мейн-цветом игрока. Неизвестный id даёт умолчание набора,
        /// индекс цвета заворачивается по набору (<see cref="PlayerColors"/>) — оба приходят снаружи,
        /// а игрок без курсора остаться не может.
        /// </summary>
        /// <remarks>
        /// Цвет здесь не украшение: свой курсор обязан выглядеть так же, как его видит напарник
        /// (заказ Макса 22.08.2026: «Цвет курсора должен меняться от выбранного цвета в профиле»).
        /// Чужие курсоры красятся тинтом в UI-слое с первого дня, а свой — системный, и красить его
        /// приходится самим, готовой текстурой.
        /// </remarks>
        void Apply(string skinId, int colorIndex);
    }
}
