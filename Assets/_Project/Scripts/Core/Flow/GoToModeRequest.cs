namespace Guildmaster.Core.Flow
{
    /// <summary>Режим верхней панели: то же, что табы «Карта», «Бой», «Инвентарь».</summary>
    public enum RunMode
    {
        Map,
        Battle,
        Inventory,
    }

    /// <summary>
    /// «Переведи меня в этот режим» — ровно то, что делает нажатие таба.
    /// </summary>
    /// <remarks>
    /// <b>Заведено 08.08.2026, чтобы кнопки были буквально табами</b> (требование Макса: «Эти 2 кнопки
    /// это буквально тот же скрипт должен быть как нажать на таб „карта“ или „бой“»). Кнопки передышки
    /// раньше публиковали свои интенты — «Продолжить» совпадал с табом «Карта» случайно, а «К строю»
    /// слал <c>SetFormationRequest</c>, которого таб «Бой» не шлёт вовсе и который слушает только
    /// хозяйская расстановка. У гостя такая кнопка не сделала бы ничего.
    /// <para><b>Обработчик один — корневой UI</b>, тот же, что обслуживает табы. Второй путь к смене
    /// режима разошёлся бы с первым ровно там, где это труднее заметить: в порядке «убрать карту,
    /// закрыть инвентарь, войти в бой».</para>
    /// </remarks>
    public readonly struct GoToModeRequest
    {
        public readonly RunMode Mode;

        public GoToModeRequest(RunMode mode) => Mode = mode;
    }
}
