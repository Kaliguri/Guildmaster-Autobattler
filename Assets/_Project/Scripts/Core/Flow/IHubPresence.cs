namespace Guildmaster.Core.Flow
{
    /// <summary>
    /// Двор гильдии глазами того, кто его не рисует: открыт ли он и надо ли его открыть.
    /// </summary>
    /// <remarks>
    /// <b>Тот же шов, что у карты акта</b> (<c>IActMapPresence</c>), и заведён по той же причине: «где
    /// мы» объявляет хост, а двор — часть этого ответа. Открывает двор петля игры (<c>GameFlow</c>),
    /// петли у гостя нет, и без объявления он оставался в предыдущем месте: хост уходил во двор, а
    /// гость смотрел на боевую камеру в пустом мире (наход. Макса 04.08.2026, прогон вдвоём).
    /// <para><b>Живёт в Core, а не рядом с картой,</b> потому что реализует его показ интерфейса
    /// (<c>MenuRouter</c>, сборка UI), а спрашивает сеанс (сборка Game). Ссылка идёт Game → UI, и общий
    /// дом у них один.</para>
    /// <para>Двух членов достаточно: спросить и объявить. Что игрок во дворе делает — наём, ростер,
    /// лавка — принадлежит самому двору, и сети там делать нечего.</para>
    /// </remarks>
    public interface IHubPresence
    {
        /// <summary>Открыт ли двор прямо сейчас. Хост объявляет это гостю, чтобы тот шёл следом.</summary>
        bool IsShown { get; }

        /// <summary>
        /// Открыть или закрыть двор. Повтор того же состояния — no-op: гость применяет объявление
        /// целиком и каждый раз, а не только на изменение.
        /// </summary>
        void SetVisible(bool visible);
    }
}
