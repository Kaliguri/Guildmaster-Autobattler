namespace Guildmaster.Core.Net
{
    /// <summary>Кто мы в этом бою.</summary>
    public enum BattleRole
    {
        /// <summary>Сети нет: считаем и показываем сами.</summary>
        Solo = 0,

        /// <summary>Мы авторитет: считаем бой и раздаём его лентой.</summary>
        Host,

        /// <summary>Мы зритель: своей симуляции нет, показываем присланную ленту.</summary>
        Guest,
    }

    /// <summary>
    /// Роль этого узла в бою. Читается каждый кадр теми, кому она меняет поведение: тиковым циклом,
    /// раздачей ленты, приёмником.
    /// </summary>
    /// <remarks>
    /// <b>Почему шов, а не чтение транспорта напрямую.</b> Боевой скоуп поднимается на буте — в
    /// главном меню, задолго до всякой сети, — поэтому роль нельзя решить регистрацией («хосту
    /// стример, гостю приёмник»): в момент <c>Configure</c> её ещё нет. Значит зарегистрировано у
    /// всех одно и то же, а расходятся узлы в рантайме — по этому свойству. Тесту при этом нужна
    /// подменяемая роль без живого транспорта, отсюда интерфейс.
    /// <para><b>Соло и хост различаются,</b> хотя оба считают бой сами: хосту надо ещё и раздавать, а
    /// соло-игрок не должен платить за нарезку чанков, которые никто не примет.</para>
    /// </remarks>
    public interface IBattleAuthority
    {
        /// <summary>Текущая роль.</summary>
        BattleRole Role { get; }

        /// <summary>
        /// Считаем ли бой сами. Гость — нет: у него нет ни своей симуляции, ни права её тикать, иначе
        /// два узла разошлись бы на первом же различии в вещественной арифметике.
        /// </summary>
        bool SimulatesLocally { get; }
    }
}
