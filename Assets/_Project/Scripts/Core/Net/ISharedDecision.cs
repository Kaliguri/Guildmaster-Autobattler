using System;

namespace Guildmaster.Core.Net
{
    /// <summary>
    /// Общее решение группы: происходит то, что выбрали ВСЕ игроки сессии, и только когда выбрали одно
    /// и то же.
    /// </summary>
    /// <remarks>
    /// <b>Заведено как общий механизм, а не как деталь PvP</b> (решение 03.08.2026). Согласия требуют и
    /// «Начать бой», и «Продолжить» после боя, и то же самое понадобится в кампании: везде, где двое
    /// смотрят на одну кнопку, вопрос один и тот же — все ли нажали. Три похожих счётчика разошлись бы
    /// на первом же расхождении, а расхождение здесь читается как зависшая кнопка.
    /// <para><b>Согласие — частный случай выбора</b> (07.08.2026). Кнопка «Начать» это решение с ОДНИМ
    /// вариантом, награда 1-из-3 — с тремя, узел карты — с числом доступных путей. Заказ Макса —
    /// «должны тыкнуть все обязательно», и он одинаков для всех троих; заводить рядом с булевым гейтом
    /// второй счётчик для голосований значило бы повторить ту же ошибку, ради которой гейт и сводили в
    /// один механизм. Новый совместный экран отсюда стоит ключа и списка вариантов, а не протокола.</para>
    /// <para><b>Расхождение НЕ разрешается само.</b> Все выбрали, но разное — решение просто не
    /// принято, и это видно. Игра не диагностирует спор и не подсовывает арбитра: ритуал (кубик, знаки)
    /// зовут сами игроки, когда захотят (канон — <c>gdd/50-modes-ux/coop/arbiters</c>, вердикт Макса
    /// 30.07.2026).</para>
    /// <para><b>Считает хост.</b> Гость отправляет свой голос и получает счёт — своего мнения о том,
    /// договорились ли все, у него нет. Это та же линия, по которой у нас устроено всё остальное: одно
    /// состояние, один владелец.</para>
    /// <para><b>В соло решение не мешает:</b> участник один, выбор свой, действие происходит в тот же
    /// кадр. Ветки «а мы одни?» в вызывающем коде быть не должно.</para>
    /// </remarks>
    public interface ISharedDecision
    {
        /// <summary>Сколько игроков уже сделали свой выбор.</summary>
        int Voted { get; }

        /// <summary>Сколько нужно — столько же, сколько игроков в сессии. В соло единица.</summary>
        int Required { get; }

        /// <summary>Выбрали ли мы сами. По второму нажатию того же варианта выбор снимается.</summary>
        bool HasLocalChoice { get; }

        /// <summary>
        /// Наш вариант; <see cref="DecisionOptions.None"/> — не выбрали. Для решения-согласия это всегда
        /// <see cref="DecisionOptions.Agree"/>, и читать его там незачем.
        /// </summary>
        string LocalChoice { get; }

        // События здесь НЕТ намеренно: гейт живёт в скоупе сеанса, а кнопка — выше него и переживает
        // несколько сеансов. Подписка на объект, который умрёт раньше подписчика, — это либо утечка,
        // либо отписка в чужой момент. Счёт вещается сообщением (SharedDecisionChangedEvent) по шине, которая
        // живёт всегда.

        /// <summary>
        /// Связать действие, которого ждём. Смена действия сбрасывает набранные голоса: выбирали одно,
        /// а случилось бы другое.
        /// </summary>
        /// <param name="key">Что решаем — «battle.start», «reward.pick». Ключ и есть смысл.</param>
        void Bind(string key, Action onAgreed);

        /// <summary>
        /// Связать решение с вариантами: действие получает то, на чём сошлись.
        /// </summary>
        /// <remarks>
        /// Список вариантов сюда НЕ передаётся намеренно. Проверять «а есть ли такой вариант» здесь
        /// нечем и незачем: варианты рождаются там же, где экран (три выпавшие мементо, доступные узлы),
        /// и второй их список тут разошёлся бы с первым ровно тогда, когда содержимое меняется на лету.
        /// Решение сравнивает голоса между собой, а не со справочником.
        /// </remarks>
        void Bind(string key, Action<string> onAgreed);

        /// <summary>Снять связанное действие: экран, который его заказывал, уходит.</summary>
        void Unbind(string key);

        /// <summary>
        /// Переключить собственное согласие — то же, что <see cref="Choose"/> с единственным вариантом.
        /// В соло сразу выполняет действие.
        /// </summary>
        void ToggleLocal();

        /// <summary>
        /// Выбрать вариант. Повтор того же варианта снимает свой голос — как второе нажатие «Готов»;
        /// другой вариант просто заменяет прежний, передумать можно без промежуточного шага.
        /// </summary>
        void Choose(string optionId);

        /// <summary>
        /// Сбросить согласие всех: то, под чем подписывались, изменилось (кто-то переставил бойца).
        /// </summary>
        void Reset(string reason);
    }
}
