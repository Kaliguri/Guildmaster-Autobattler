namespace Guildmaster.Core.Net
{
    /// <summary>
    /// Ключи гейта готовности: что именно подтверждают участники.
    /// </summary>
    /// <remarks>
    /// Ключ — это ДОГОВОР между тем, кто объявляет согласие, и тем, кто рисует счёт: по нему
    /// подписчик отличает свой счёт от чужого (<see cref="SharedDecisionChangedEvent.Key"/>). Пока ключи
    /// жили литералами в трёх файлах, договор держался только на том, что все три строки совпадают, —
    /// и топбар, забывший сверить ключ, показывал на кнопке «Начать» счёт гейта возврата к расстановке.
    /// </remarks>
    public static class DecisionKeys
    {
        /// <summary>Согласие начать бой.</summary>
        public const string BattleStart = "battle.start";

        /// <summary>Согласие уйти с экрана исхода обратно к расстановке.</summary>
        public const string BattleContinue = "battle.continue";

        /// <summary>Какую из выпавших реликвий забирает группа. Вариант — id реликвии.</summary>
        public const string RewardPick = "reward.pick";

        /// <summary>Куда идём по карте акта. Вариант — id узла.</summary>
        public const string MapNode = "map.node";

        /// <summary>Согласие открыть сундук. За крышкой общая награда, значит и крышка общая.</summary>
        public const string ChestOpen = "chest.open";

        /// <summary>
        /// Какой ответ на текстовое событие берёт группа. Вариант — НОМЕР строки в списке ответов.
        /// </summary>
        /// <remarks>
        /// Номер, а не текст ответа: варианты приходят из одного и того же ассета события, а вот его
        /// строки переводятся и правятся. Сравнивай мы переведённый текст — голоса разошлись бы у
        /// игроков с разным языком.
        /// </remarks>
        public const string EventChoice = "event.choice";

        /// <summary>
        /// Куда группа идёт с экрана исхода забега. Варианты — <see cref="RunAfterOptions"/>.
        /// </summary>
        /// <remarks>
        /// <b>Одно решение с двумя вариантами, а не два решения.</b> Механизм держит один заказ за раз,
        /// и второй <c>Bind</c> обнулил бы голоса первого — на экране с двумя общими кнопками это
        /// выглядело бы как «нажал, а счёт пропал». Заодно оно честнее: один хочет заново, другой во
        /// двор — голоса не сходятся, и обоим видно, кто что выбрал.
        /// <para><b>«В главное меню» сюда НЕ входит</b> — эта кнопка личная (вердикт Макса 08.08.2026):
        /// уйти к себе можно, не спрашивая напарника.</para>
        /// </remarks>
        public const string RunAfter = "run.after";
    }

    /// <summary>Куда группа идёт после забега.</summary>
    public static class RunAfterOptions
    {
        /// <summary>Новый забег тем же домом, мимо двора.</summary>
        public const string Restart = "restart";

        /// <summary>Во двор гильдии: забег окончен, дом остаётся.</summary>
        public const string Guild = "guild";
    }

    /// <summary>
    /// Варианты решения, у которого выбор ровно один — «да».
    /// </summary>
    /// <remarks>
    /// Кнопка «Начать» и «Продолжить» — это решение с ОДНИМ вариантом: соглашаешься или нет. Оно
    /// частный случай общего, а не отдельный механизм, поэтому и голос у него обычный — просто всегда
    /// один и тот же. Пока у согласия был свой булев путь рядом с выбором из нескольких, это были два
    /// счётчика с одинаковой судьбой: разошлись бы они на первом же расхождении, а расхождение здесь
    /// читается как зависшая кнопка.
    /// </remarks>
    public static class DecisionOptions
    {
        /// <summary>«Я за» — единственный вариант решения-согласия.</summary>
        public const string Agree = "agree";

        /// <summary>«Голоса нет»: не выбрал ещё или снял свой выбор.</summary>
        public const string None = "";
    }
}
