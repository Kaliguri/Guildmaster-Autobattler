using System;

namespace Guildmaster.Core.Net
{
    /// <summary>
    /// Общее согласие: действие происходит, когда его подтвердили ВСЕ игроки сессии.
    /// </summary>
    /// <remarks>
    /// <b>Заведено как общий механизм, а не как деталь PvP</b> (решение 03.08.2026). Согласия требуют и
    /// «Начать бой», и «Продолжить» после боя, и то же самое понадобится в кампании: везде, где двое
    /// смотрят на одну кнопку, вопрос один и тот же — все ли нажали. Три похожих счётчика разошлись бы
    /// на первом же расхождении, а расхождение здесь читается как зависшая кнопка.
    /// <para><b>Считает хост.</b> Гость отправляет согласие и получает счёт готовых — своего мнения о
    /// том, все ли готовы, у него нет. Это та же линия, по которой у нас устроено всё остальное: одно
    /// состояние, один владелец.</para>
    /// <para><b>В соло гейт не мешает:</b> участник один, согласие своё, действие происходит в тот же
    /// кадр. Ветки «а мы одни?» в вызывающем коде быть не должно.</para>
    /// </remarks>
    public interface IReadyGate
    {
        /// <summary>Сколько игроков уже подтвердили.</summary>
        int Ready { get; }

        /// <summary>Сколько нужно — столько же, сколько игроков в сессии. В соло единица.</summary>
        int Required { get; }

        /// <summary>Подтвердили ли мы сами. По второму нажатию согласие снимается.</summary>
        bool LocallyReady { get; }

        // События здесь НЕТ намеренно: гейт живёт в скоупе сеанса, а кнопка — выше него и переживает
        // несколько сеансов. Подписка на объект, который умрёт раньше подписчика, — это либо утечка,
        // либо отписка в чужой момент. Счёт вещается сообщением (ReadyGateChangedEvent) по шине, которая
        // живёт всегда.

        /// <summary>
        /// Связать действие, которого ждём. Смена действия сбрасывает набранное согласие: подтверждали
        /// одно, а случилось бы другое.
        /// </summary>
        /// <param name="key">Что подтверждаем — «battle.start», «battle.continue». Ключ и есть смысл.</param>
        void Bind(string key, Action onAllReady);

        /// <summary>Снять связанное действие: экран, который его заказывал, уходит.</summary>
        void Unbind(string key);

        /// <summary>Переключить собственное согласие. В соло сразу выполняет действие.</summary>
        void ToggleLocal();

        /// <summary>
        /// Сбросить согласие всех: то, под чем подписывались, изменилось (кто-то переставил бойца).
        /// </summary>
        void Reset(string reason);
    }
}
