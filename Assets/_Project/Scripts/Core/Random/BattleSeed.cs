namespace Guildmaster.Core.Random
{
    /// <summary>
    /// Сид текущего боя — единый доступ к нему из DI. Держатель, а не генератор:
    /// значение выбирается на старте боя (случайно или фиксировано для воспроизводимости),
    /// кладётся сюда и раздаётся всем, кому нужен детерминизм по имени, а не по приватной генерации.
    /// <para>Зачем отдельный тип: сид — вход детерминированной симуляции. Чтобы позже писать
    /// реплеи/спектейт и синхронизировать RNG в MP (сид приходит от хоста), его нужно
    /// уметь прочитать, а не только «где-то внутри» сгенерировать (см. <see cref="XorShiftRng"/>).</para>
    /// </summary>
    public sealed class BattleSeed
    {
        /// <summary>Сид, из которого выведено состояние RNG этого боя.</summary>
        public ulong Value { get; }

        public BattleSeed(ulong value) => Value = value;
    }
}
