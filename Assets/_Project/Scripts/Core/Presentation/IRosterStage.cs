using UnityEngine;

namespace Guildmaster.Core.Presentation
{
    /// <summary>
    /// «Живая арена расстановки» вне боя (Ф3b): персистентная лёгкая сцена отряда игрока, рендеримая в
    /// <see cref="RenderTexture"/> и показываемая «окном в мир» в левой зоне экрана инвентаря. Строится
    /// ON-DEMAND при открытии инвентаря, разбирается при закрытии — персистентность позиций даёт
    /// durable RunState, а не живые объекты. Реализация лежит в Game-слое (нужен доступ к Presentation
    /// и гильдии); UI держит лишь этот интерфейс и нейтральную RT.
    /// <para>Ф3b.1 — статичное окно + отряд. Управление камерой (пан/зум), драг релик→эквип и durable
    /// позиции добавляются в под-фазах .2–.4.</para>
    /// </summary>
    public interface IRosterStage
    {
        /// <summary>Открыто ли окно (стейдж построен).</summary>
        bool IsOpen { get; }

        /// <summary>Текущая RT окна (null, если закрыто) — для показа фоном UI-элемента.</summary>
        RenderTexture Texture { get; }

        /// <summary>
        /// Построить стейдж (мок-арена + отряд из гильдии) и камеру, отдать её <see cref="RenderTexture"/>
        /// заданного пиксельного размера для показа в UI. Повторный вызов на открытом окне возвращает
        /// текущую RT. Пустая гильдия → демо-отряд (dev-стенд без забега).
        /// </summary>
        RenderTexture Open(int width, int height);

        /// <summary>Разобрать стейдж, камеру и освободить RT. Идемпотентно.</summary>
        void Close();

        /// <summary>
        /// Панорама камеры «схватом мира»: сдвиг задаётся ДОЛЕЙ вьюпорта (пиксельная дельта курсора ÷ размер
        /// окна), контроллер переводит её в мировые единицы по текущему зуму. Клампится зоной арены (Ф3b.2).
        /// </summary>
        void PanByFraction(Vector2 fractionDelta);

        /// <summary>Зум камеры шагами (колесо): +1 приближает, −1 отдаляет. Клампится [мин; вся арена].</summary>
        void ZoomBy(float steps);
    }
}
