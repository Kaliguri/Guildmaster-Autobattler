using System;

namespace Guildmaster.Core.Arena
{
    /// <summary>
    /// Смена облика арены «А → Б» в цифровом стиле (три акта, см. <see cref="ArenaSwapShape"/>).
    /// Заказчик только просит скин и, если надо, узнаёт о конце — вся анимация и владение временем
    /// внутри реализации.
    /// <para>Живёт в мире (persist-скоуп), а не в боевом: переход обязан доигрывать, даже если заказчик
    /// (бой, экран, вью карты) успел исчезнуть. Ровно на этом обжигались со шторкой перехода — там
    /// владельцем была карта, и её скрытие обрывало анимацию на пике (QA #53).</para>
    /// </summary>
    public interface IArenaSwap
    {
        /// <summary>Идёт ли переход прямо сейчас.</summary>
        bool Busy { get; }

        /// <summary>Какой скин надет сейчас (или к какому идём, пока <see cref="Busy"/>).</summary>
        string CurrentSkinId { get; }

        /// <summary>
        /// Перевести арену на скин <paramref name="skinId"/>. false — скина нет либо он уже надет.
        /// Повторный вызов во время перехода игнорируется (кроме случая, когда просят тот же скин —
        /// это не ошибка, просто ничего не делаем).
        /// </summary>
        bool Play(string skinId, Action onFinished = null);

        /// <summary>
        /// Резко ускорить текущий переход (Space). Не обрывает картинку скачком: анимация та же,
        /// просто время бежит быстрее — иначе на полутора десятках узлов за забег красота станет налогом.
        /// </summary>
        void Rush();

        /// <summary>Мгновенно надеть скин без анимации: загрузка сейва, первый вход в мир, dev-команды.</summary>
        void ApplyInstant(string skinId);
    }
}
