using System.Collections.Generic;
using UnityEngine;

namespace Guildmaster.Core.Arena
{
    /// <summary>
    /// Один боец на арене глазами того, кто с ним ВЗАИМОДЕЙСТВУЕТ: столько, сколько нужно, чтобы его
    /// найти под курсором, обвести кругом и понять, куда он встанет.
    /// </summary>
    /// <remarks>
    /// Это не снимок и не боевая сущность, а их общий знаменатель. Полей ровно пять, и расширять их
    /// «на всякий случай» не следует: как только сюда попадёт что-то, чего нет у одной из сторон
    /// шва, шов перестанет быть общим — а он существует ровно ради того, чтобы руки игрока работали
    /// одинаково у хозяина сеанса и у гостя.
    /// </remarks>
    public readonly struct ArenaUnit
    {
        /// <summary>Ключ, по которому показ находит вид, а расстановка — слот.</summary>
        public readonly int Id;

        /// <summary>Сторона арены. Кому она подчиняется — вопрос не сюда, а к составу сеанса.</summary>
        public readonly int Team;

        public readonly Vector2 Position;

        /// <summary>Габарит тела в единицах статов; в радиус переводит боевая геометрия.</summary>
        public readonly float Size;

        public readonly bool IsDead;

        public ArenaUnit(int id, int team, Vector2 position, float size, bool isDead)
        {
            Id       = id;
            Team     = team;
            Position = position;
            Size     = size;
            IsDead   = isDead;
        }
    }

    /// <summary>
    /// Кто сейчас стоит на арене. Единственный источник этого факта для всего, что игрок делает
    /// руками: круги-опоры, выбор бойца под курсором, проверка «не встанет ли на соседа».
    /// </summary>
    /// <remarks>
    /// <b>Почему шов, а не прямое обращение к симуляции.</b> У хозяина сеанса правду о позициях
    /// держит живая симуляция — там перетаскивание видно в тот же кадр. У гостя симуляции нет вовсе
    /// (он бы затёр ею присланную ленту), и правду держит присланный кадр. Пока расстановка
    /// спрашивала симуляцию напрямую, у гостя она видела пустую арену — отсюда и «не вижу кругов, не
    /// могу перетащить», и то, что это читалось как три разных бага вместо одного.
    /// <para><b>Мёртвых отсюда не выкидываем.</b> Кто их пропускает — дело потребителя: расстановка
    /// пропускает, а вот проверка перекрытия обязана знать о теле, которое ещё лежит на арене.</para>
    /// </remarks>
    public interface IArenaUnits
    {
        /// <summary>Все, кто на арене сейчас. Пустой список — арена пуста, и это не отказ.</summary>
        IReadOnlyList<ArenaUnit> Units { get; }

        /// <summary>
        /// Найти бойца по id. <c>false</c> — его на арене больше нет (респавн превью, смерть, конец
        /// боя), и это нормальный ответ: id живёт меньше, чем указатель игрока на него.
        /// </summary>
        bool TryGet(int id, out ArenaUnit unit);
    }
}
