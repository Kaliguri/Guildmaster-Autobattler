using System.Collections.Generic;

namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Компонент эффекта, который добавляет носителю <b>статический источник урона</b> — то есть
    /// собственный тип урона, не сводимый к автоатаке кита и его способностям. Носитель сегодня один:
    /// боевые стойки, у каждой формы свой тип.
    /// </summary>
    /// <remarks>
    /// <b>Зачем интерфейс, а не проверка конкретного типа.</b> Спрашивает <see cref="UnitTagResolver"/>,
    /// который живёт в <c>Data</c>, а компоненты — в <c>Combat</c>, слое выше: снизу вверх смотреть
    /// нельзя, и до этого интерфейса типы форм в чипы карточки просто не доходили — кит со стойками
    /// показывал только одну свою форму, ту, что записана в ките.
    /// <para><b>Это про ФОРМЫ, а не про эффекты вообще.</b> Урон, который эффект наносит САМ (тик
    /// поджога, споры), сюда не относится: он свойство эффекта на цели, а не оружия носителя, и его
    /// путь в чипы — отдельная развилка про сродства.</para>
    /// </remarks>
    public interface IDeclaresDamageTypes : IEffectComponent
    {
        /// <summary>
        /// Дописать типы урона, которые компонент даёт носителю. Дубликаты допустимы — их отсеивает
        /// вызывающий; <see cref="DamageType.Undefined"/> добавлять не нужно.
        /// </summary>
        void CollectDamageTypes(ICollection<DamageType> into);
    }
}
