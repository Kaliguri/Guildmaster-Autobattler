namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Форма зоны поражения авто-атаки/способности (вики «13», шаг 4; «6» §10).
    /// Опора AOE-паттернов: линейная авто-атака («Размашистый выпад») и круговой удар
    /// вокруг себя («Стальной вихрь»). <see cref="None"/> = одиночная цель (поведение Ф1/Ф2).
    /// </summary>
    public enum AreaShape
    {
        /// <summary>Одиночная цель (без зоны). Дефолт — не меняет поведение существующего контента.</summary>
        None = 0,

        /// <summary>Линия перед юнитом в сторону цели: длина = радиус атаки, ширина — отдельным полем.</summary>
        Line = 1,

        /// <summary>Круг вокруг точки (обычно вокруг себя): радиус — отдельным полем.</summary>
        Circle = 2,
    }
}
