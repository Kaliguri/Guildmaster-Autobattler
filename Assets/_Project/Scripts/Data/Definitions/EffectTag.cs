using System;

namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Категориальные теги эффекта: для диспела по категории, AI-фильтров и быстрой
    /// битовой маски активных эффектов на юните (вики «6» §5.3–§5.4, «12» §2.1).
    /// <c>[Flags]</c> — один эффект может нести несколько категорий (напр. Debuff | DoT).
    /// </summary>
    [Flags]
    public enum EffectTag
    {
        None    = 0,
        Buff    = 1 << 0,
        Debuff  = 1 << 1,
        Control = 1 << 2,
        DoT     = 1 << 3,
        HoT     = 1 << 4,
        Heal    = 1 << 5,
        Shield  = 1 << 6,

        // --- Контентные категории Фазы 3 (вики «13» §2.6) ---

        /// <summary>Криомант: пассивка-АА ставит, активка станит всех с этим тегом (TaggedTargetsCount).</summary>
        Frozen  = 1 << 7,

        /// <summary>Лесной следопыт: метка +25% урона; AI-приоритет PreferTagged(Marked); перенос при смерти.</summary>
        Marked  = 1 << 8,

        /// <summary>Семейство контроллеров: «подкидывание» — контроль, НЕ скейлится ReceiveDebuffEff (§4.4).</summary>
        KnockUp = 1 << 9,

        /// <summary>Скрытный убийца: баф «Скрытность» — снимается первой авто-атакой (§9.6, §10.5).</summary>
        Stealth = 1 << 10,

        /// <summary>Друид: категория «Яд». «Взрыв спор» детонирует всех врагов с этим тегом (как «Заморозка» у крио).</summary>
        Poison  = 1 << 11,

        /// <summary>Огненный мечник: «Поджог». «Воспламенение» детонирует стаки на цели.</summary>
        Burn    = 1 << 12,

        /// <summary>«Угли» на цели: копятся от урона огнём, усиливают огонь по ней, тратятся детонацией.</summary>
        Ember   = 1 << 13,

        /// <summary>
        /// Взведённый заряд усиленной авто-атаки, НЕ связанный со скрытностью («Восходящий удар» Монаха
        /// воды). Носит тот эффект, который заряд выдал: удар снимает его по этому тегу и не трогает стелс.
        /// </summary>
        Empowered = 1 << 14,

        /// <summary>
        /// Сон: контроль, который снимается ЧУЖИМ уроном и потому требует своего тега — целеуказание
        /// обходит спящих («Колыбельная» Пожирателя снов), а диспел сна не должен снимать заодно оглушения.
        /// </summary>
        Sleep = 1 << 15,

        /// <summary>
        /// «Изморозь» — стаки холодной линии. Отдельно от <see cref="Frozen"/> намеренно: <c>Frozen</c>
        /// достался верхней ступени («обратился в лёд»), и по нему AI ищет цель, УЖЕ оглушённую холодом.
        /// Один тег на оба состояния означал бы, что условие «рядом есть статуя» ловит любую подмёрзшую цель.
        /// </summary>
        Frostbite = 1 << 16,
    }
}
