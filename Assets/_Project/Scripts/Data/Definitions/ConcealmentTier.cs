namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Ступень Маскировки — насколько близко нужно подойти, чтобы увидеть носителя (дизайн Макса
    /// 2026-07-30, числа 2026-07-31). Радиусы живут не здесь, а в <c>SimTuningConfig</c>: ступень —
    /// свойство кита, а расстояние — балансная ручка игры.
    /// </summary>
    /// <remarks>
    /// Порядок значений — по силе, и на это опирается код: при нескольких источниках маскировки
    /// побеждает <b>больший</b> tier. Вставлять новые ступени в середину нельзя, не переставив числа.
    /// </remarks>
    public enum ConcealmentTier
    {
        /// <summary>Не замаскирован — обычный юнит.</summary>
        None = 0,

        /// <summary>Слабая: видно издалека (радиус обнаружения ~6).</summary>
        Weak = 1,

        /// <summary>Средняя (~4).</summary>
        Medium = 2,

        /// <summary>Сильная: заметен только вплотную (~2).</summary>
        Strong = 3,

        /// <summary>
        /// Инвиз: не обнаруживается вовсе, сколько ни подходи. Снять его можно только своим действием —
        /// атакой или кастом. Это та невидимость, в которой сегодня живёт «Скрытность» Убийцы.
        /// </summary>
        Invisible = 4,
    }
}
