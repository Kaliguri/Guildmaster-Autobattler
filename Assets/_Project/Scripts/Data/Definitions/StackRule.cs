namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Поведение при повторном наложении того же эффекта на цель (вики «6» §5.3).
    /// </summary>
    public enum StackRule
    {
        /// <summary>Повтор игнорируется — существующий экземпляр не трогаем.</summary>
        None = 0,

        /// <summary>Добавить стак (до <c>MaxStacks</c>); длительность не обновлять.</summary>
        Stack = 1,

        /// <summary>Обновить длительность до полной; стаки не трогать.</summary>
        Refresh = 2,

        /// <summary>Добавить стак И обновить длительность.</summary>
        StackAndRefresh = 3,

        /// <summary>
        /// Каждое наложение — <b>своя порция</b> со своей силой и своим сроком. Порции копятся, их вклад
        /// суммируется, и каждая сходит отдельно; эффект висит, пока жива хоть одна. Потолка нет.
        /// Носитель — Кровотечение.
        /// </summary>
        /// <remarks>
        /// <b>Четвёртое правило, а не флаг рядом с тремя</b> (решение Макса 2026-07-30). Остальные три
        /// стоят на модели «одна сила и один срок на всех, плюс счётчик»: сила снимается со статов
        /// ПЕРВОГО наложившего и рестаком не обновляется. Для крови это неверно вдвойне — второй
        /// кровоточащий кит в отряде молча раздавал бы силу первого, а «кровотечение силой 30% от МОЕГО
        /// удара» стало бы невыразимым.
        /// <para>Правило объявляется явно именно потому, что смешивать модели нельзя: эффект с порциями
        /// читает <c>RuntimeEffect.PortionRate</c>, эффект со стаками — <c>ScaledPotency</c> и
        /// <c>VisibleStacks</c>, и молчаливое совпадение здесь дало бы DoT, который бьёт то одним, то
        /// другим.</para>
        /// </remarks>
        Portions = 4,
    }
}
