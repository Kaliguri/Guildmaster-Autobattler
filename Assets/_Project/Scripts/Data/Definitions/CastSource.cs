namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Чем юнит исполняет приём — какая его часть является источником: клинок, щит, вторая рука, всё
    /// тело. Показ по этому полю решает, ЧТО зажечь на телеграфе каста.
    /// </summary>
    /// <remarks>
    /// Это дизайн-факт, а не техническая деталь: «щит-бэш светится щитом», «залп двумя кинжалами —
    /// обоими», «марш — свечение тела, не оружия». Вывести его из механики нельзя — способность с
    /// уроном может быть и ударом клинка, и пинком.
    /// <para>
    /// Названы РОЛИ в бою, а не узлы рига: конкретную часть находит реестр частей юнита по его
    /// расстановке (<c>IUnitPartLookup</c>). Поэтому один и тот же <see cref="OffHand"/> у бойца с
    /// двумя кинжалами зажжёт левый кинжал, а у бойца со щитом — щит.
    /// </para>
    /// </remarks>
    public enum CastSource
    {
        /// <summary>Чем юнит бьёт обычно: предмет в ведущей руке, а у безоружного — его кулак.</summary>
        Auto = 0,

        /// <summary>Вторая рука: второй клинок дуалиста, щит у щитовика.</summary>
        OffHand = 1,

        /// <summary>Обе руки разом — залп двумя клинками, удар с двух рук.</summary>
        BothHands = 2,

        /// <summary>Именно щит, в какой бы руке он ни был (щит-бэш, парирование).</summary>
        Shield = 3,

        /// <summary>Всё тело — длительные баффы, ауры, марши: свет идёт от юнита, а не от оружия.</summary>
        WholeBody = 4,

        /// <summary>Ничего не светится: приём подан другими средствами (звук, зона, снаряд).</summary>
        None = 5,
    }
}
