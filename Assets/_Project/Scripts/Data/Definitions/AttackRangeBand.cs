namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Ступень дальности авто-атаки: <b>каждый юнит выбирает одну из шести</b>, а число за ней живёт в
    /// <see cref="StatsConfig"/>. Персональная поправка задаётся долей от ступени, а не своим числом.
    /// </summary>
    /// <remarks>
    /// <para><b>Зачем ступени, а не число у каждого.</b> Пока дальность была свободным полем, у неё не было
    /// ни владельца, ни словаря: незаданное поле молча уезжало на дефолт конфига (единицу), и дальник
    /// оказывался вплотную к цели, не сообщая об этом ничем. Так вышло с Кровомантом — РДД со снарядом,
    /// дравшийся в упор. Ступень отвечает на вопрос «кто он по дистанции» ДО того, как кто-то назначит
    /// число.</para>
    /// <para><b>Зачем поправка в долях.</b> Ступени — ручка баланса: сдвинули «обычного дальника» с восьми
    /// на семь, и все обычные дальники поехали вместе. Поправка в мировых единицах это ломает — кит с
    /// «+1» остался бы на прежней дистанции, — поэтому она долевая и намеренно мелкая.</para>
    /// <para><b>Почему у «без ограничений» есть число.</b> На дальность опираются геометрические гейты:
    /// предсказание «замах докрутит», сближение, кайтинг. Бесконечность превратила бы их в сравнение с
    /// бесконечностью, поэтому шестая ступень — просто число крупнее любой арены (поле 20×12, диагональ
    /// около 23).</para>
    /// </remarks>
    public enum AttackRangeBand
    {
        /// <summary>Обычный ближний бой: меч, кулак, коготь.</summary>
        Melee = 0,

        /// <summary>Ближний с длинным оружием: копьё, алебарда, хлыст.</summary>
        Reach = 1,

        /// <summary>Дальний с малой дистанцией: метатель, короткий каст.</summary>
        ShortRange = 2,

        /// <summary>Обычный дальний: лук, посох, большинство заклинателей.</summary>
        MidRange = 3,

        /// <summary>Дальний с большой дистанцией: снайпер, дальнобойная магия.</summary>
        LongRange = 4,

        /// <summary>Бьёт через всю арену — ограничения по дистанции у него фактически нет.</summary>
        Boundless = 5,
    }
}
