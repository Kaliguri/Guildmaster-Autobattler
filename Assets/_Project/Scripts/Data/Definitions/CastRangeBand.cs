namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Дальность каста умения — те же ступени, что у авто-атаки, плюс дефолт «как у неё».
    /// </summary>
    /// <remarks>
    /// <para><b>Почему дефолт наследует, а не требует выбора.</b> Обычно умение достаёт оттуда же,
    /// откуда кит бьёт рукой: лучник стреляет умением с восьми, мечник бьёт с единицы. Заставлять
    /// автора называть ступень каждому умению значило бы плодить возможность разойтись на ровном месте.
    /// Своя ступень нужна там, где умение достаёт иначе, чем оружие, — и тогда это осознанное решение,
    /// а не забытое поле.</para>
    /// <para><b>Дальность есть не у всякого умения.</b> Она измеряется до ЦЕЛИ, поэтому у умений без
    /// внешней цели её нет в принципе: каст на себя, аура по своим, круг вокруг себя, масс-по-тегу.
    /// Копейщик кастует вихрь с центром на себе — вопрос «с какой дистанции» к нему просто не задаётся,
    /// зато задаётся другой, «зацепит ли хоть кого-то», и на него отвечает условие каста.</para>
    /// </remarks>
    public enum CastRangeBand
    {
        /// <summary>Как у авто-атаки этого юнита — дефолт.</summary>
        LikeAutoAttack = 0,

        /// <summary>Ближний бой.</summary>
        Melee = 1,

        /// <summary>Длинное оружие.</summary>
        Reach = 2,

        /// <summary>Малая дистанция.</summary>
        ShortRange = 3,

        /// <summary>Обычная дистанция.</summary>
        MidRange = 4,

        /// <summary>Большая дистанция.</summary>
        LongRange = 5,

        /// <summary>Через всю арену.</summary>
        Boundless = 6,
    }
}
