using UnityEngine;

namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Скин курсора: чем игрок выглядит для себя и для остальных.
    /// </summary>
    /// <remarks>
    /// <b>Курсор — главная вещь, которую видят другие игроки,</b> поэтому он же главный предмет
    /// косметики (кооп-кластер ГДД, presence §Что курсор несёт). Отсюда и отдельный контент-тип: скин
    /// должен уметь выдаваться за «Мелочь Гильдмастера» и ехать по сети рядом с мейн-цветом.
    /// <para><b>Текстура белая с чёрной обводкой — это условие, а не случайность.</b> Цвет игрока
    /// накладывается тинтом (умножением): белая заливка становится мейн-цветом, обводка остаётся
    /// чёрной и держит курсор читаемым на светлой карте и на тёмной арене. Цветной скин красить было
    /// бы нечем.</para>
    /// <para><b>Величину скинов сводит не глаз, а <c>scripts/cursors-build.py</c>:</b> у всех
    /// совпадает диагональ фигуры, потому что исходники разъезжаются почти вдвое при одинаковом
    /// холсте. Новый скин собирается тем же скриптом, иначе он выпадет из набора по величине.</para>
    /// </remarks>
    [CreateAssetMenu(menuName = "Guildmaster/Content/Cursor Skin", fileName = "CursorSkin")]
    public sealed class CursorSkinData : ContentDefinition
    {
        [Header("Изображение")]
        [Tooltip("Текстура курсора: белая фигура с чёрной обводкой на прозрачном фоне, холст 320x320. " +
                 "Собирается scripts/cursors-build.py из вектора — руками не масштабировать.")]
        [SerializeField] private Texture2D _texture;

        [Header("Остриё")]
        [Tooltip("Точка, которой курсор указывает, долями текстуры (0,0 — левый верхний угол). " +
                 "Задаётся вручную: направление у скинов разное, и вывести остриё из картинки нельзя.")]
        [SerializeField] private Vector2 _hotspot = new Vector2(0.06f, 0.04f);

        /// <summary>Изображение курсора.</summary>
        public Texture2D Texture => _texture;

        /// <summary>
        /// Остриё в долях текстуры. Долями, а не пикселями: холст скина может смениться, а «куда
        /// показывает стрелка» от размера картинки не зависит.
        /// </summary>
        public Vector2 Hotspot => _hotspot;

        /// <summary>Остриё в пикселях текущей текстуры — в таком виде его ждёт системный курсор.</summary>
        public Vector2 HotspotPixels => _texture == null
            ? Vector2.zero
            : new Vector2(_hotspot.x * _texture.width, _hotspot.y * _texture.height);
    }
}
