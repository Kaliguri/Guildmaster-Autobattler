namespace Guildmaster.Data.Definitions
{
    /// <summary>
    /// Id контента, на которые завязан САМ КОД, — здесь и только здесь.
    /// <para>Обычный контент код по id не знает: он приходит из данных и резолвится через
    /// <see cref="IContentDatabase"/>. Но пара сущностей особенная — на них код опирается структурно
    /// (фолбэк для пустого слота, исключение из витрины наград), и их id неизбежно попадает в исходники.
    /// Такой id обязан жить в одном месте: до аудита 2026-07-26 строка <c>"relic.base"</c> была выписана
    /// в семи файлах, и переименование контента сломало бы игру молча — часть мест продолжила бы искать
    /// старый id и тихо откатываться на «слот пропущен» (R1-50).</para>
    /// <para>Это НЕ то же самое, что <c>GameConfig.StartingRelicId</c>. Тот отвечает на вопрос «с чего
    /// начинается забег» и настраивается дизайнером; этот — «id базового кита», структурный фолбэк.
    /// Сегодня они совпадают, но менять их можно порознь.</para>
    /// </summary>
    public static class ContentIds
    {
        /// <summary>
        /// Базовый кит: подставляется, когда у слота гильдии нет реликвии, и исключается из наград и
        /// витрин, чтобы игрок не получал в награду то, что у него есть с самого начала.
        /// </summary>
        public const string BaseRelic = "relic.base";
    }
}
