namespace Guildmaster.Data.Descriptions
{
    /// <summary>
    /// Оформление термина в тексте: чем обернуть слово, чтобы оно читалось как термин.
    /// </summary>
    /// <remarks>
    /// Интерфейс живёт в слое данных, а реализация — в UI, и это не формальность. Цвета лежат в USS
    /// (единственный владелец палитры), rich text читать USS-переменные не умеет, а заводить вторую
    /// палитру в C# запрещено правилом единого источника. Значит, слой описаний обязан уметь
    /// собирать текст, НЕ зная про цвета вообще: он просит обёртку у того, кто цвета видит.
    /// <para><c>null</c>-реализация — законный случай: тесты и места без rich text получают чистый
    /// текст со скобками.</para>
    /// </remarks>
    public interface IKeywordStyle
    {
        /// <summary>Открывающие теги для термина (<c>&lt;b&gt;&lt;color=#…&gt;</c>); пусто — без оформления.</summary>
        string Open(string keywordId);

        /// <summary>Закрывающие теги в обратном порядке; пусто, если <see cref="Open"/> вернул пусто.</summary>
        string Close(string keywordId);
    }
}
