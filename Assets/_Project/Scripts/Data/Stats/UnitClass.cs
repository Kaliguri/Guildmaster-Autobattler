namespace Guildmaster.Data.Stats
{
    /// <summary>
    /// Боевой класс юнита — типизированная ось, задающая базовый баланс HP и скорости передвижения
    /// (ГДД «Combat - Stats» §Классы, решение 2026-07-24). Класс — механический вход (от него
    /// считаются числа через <c>ClassBalanceConfig</c>), а не только ярлык для UI; из него же
    /// авто-выводится role-тег юнита.
    /// </summary>
    /// <remarks>
    /// Эталон 100% — <see cref="Bruiser"/> (золотая середина). Значение <c>0</c> = Bruiser: юнит без
    /// явно заданного класса получает нейтральную базу-эталон. Номера присвоены явно и стабильны —
    /// Unity сериализует enum по int, сдвиг сломает уже настроенные поля юнитов.
    /// </remarks>
    public enum UnitClass
    {
        /// <summary>Золотая середина: 100% HP / 100% скорости. Эталон баланса и дефолт поля.</summary>
        Bruiser = 0,

        /// <summary>Держит фронт: 150% HP / 85% скорости. Живучий и медленный.</summary>
        Tank = 1,

        /// <summary>Мили-ДД: 75% HP / 110% скорости. Хрупкий и быстрый, врывается в бэклайн.</summary>
        Assassin = 2,

        /// <summary>Дальний урон: 65% HP / 75% скорости. Самый хрупкий, самый медленный.</summary>
        Ranged = 3,

        /// <summary>Хил/баффы: 65% HP / 75% скорости. Держится строем.</summary>
        Support = 4,

        /// <summary>Повелитель армии: 65% HP / 75% скорости. Сам слаб, силён призывами.</summary>
        Summoner = 5,
    }
}
