namespace Guildmaster.Data.Stats
{
    /// <summary>
    /// Канонический список боевых статов: 30 из вики «11. Стат-система (полный список статов)»
    /// плюс дописанные по решениям Макса (сила призывов, скорость набора ресурса) — всего 33.
    /// Все значения присвоены явно и стабильны:
    /// Unity сериализует enum по int, поэтому порядок/номера менять НЕЛЬЗЯ (сломает .asset).
    /// </summary>
    /// <remarks>
    /// Фаза 1 реально использует 19 статов (авто-атаки без эффектов/способностей/ресурсов) —
    /// помечены [Ф1]. Остальные объявлены сразу (список финализирован), но дефолты/клампы/логика
    /// для них подключаются в своих фазах.
    /// </remarks>
    public enum StatType
    {
        // --- §3.1 Выживаемость ---
        MaxHP = 0,              // [Ф1]
        HpRegenFlat = 1,        // [Ф1]
        HpRegenPct = 2,         // [Ф1]
        PhysArmor = 3,          // [Ф1]
        MagicArmor = 4,         // [Ф1] одна броня на всю магию (Огонь/Лёд/Молния/Аркана)
        DamageTakenEff = 5,     // [Ф1] PercentMult, старт 1.0
        HealShieldTakenEff = 6, // Ф2

        // --- §3.2 Атака ---
        AutoAttackDamage = 7,   // [Ф1]
        AttackSpeed = 8,        // [Ф1] атак/сек, клампится из StatsConfig
        AttackRange = 9,        // [Ф1]
        AbilityPower = 10,      // Ф2
        PhysPen = 11,           // [Ф1] плоское пробивание
        PhysPenPct = 12,        // [Ф1] % пробивание [0,1]
        MagicPen = 13,          // [Ф1] плоское магическое пробивание
        MagicPenPct = 14,       // [Ф1] % магическое пробивание [0,1]
        DamageDealtEff = 15,    // [Ф1] PercentMult, старт 1.0
        Lifesteal = 16,         // [Ф1] % от нанесённого урона

        // --- §3.3 Исцеление / щиты ---
        HealShieldDealtEff = 17, // Ф2

        // --- §3.4 Снаряд ---
        ProjectileSpeed = 18,   // [Ф1]
        ProjectilePierce = 19,  // [Ф1] кол-во целей, целое

        // --- §3.5 Подвижность ---
        MoveSpeed = 20,         // [Ф1]
        Size = 21,              // [Ф1] старт 1.0

        // --- §3.6 Эффективность эффектов (масштабируют ТОЛЬКО длительность) ---
        ApplyBuffEff = 22,      // Ф2
        ApplyDebuffEff = 23,    // Ф2
        ReceiveBuffEff = 24,    // Ф2
        ReceiveDebuffEff = 25,  // Ф2 (= tenacity)
        CooldownEff = 26,       // Ф2

        // --- §3.7 Ресурс (только геройские мементо) ---
        MaxResource = 27,       // Ф2
        StartResource = 28,     // Ф2 (init-only)
        ResourceGainEff = 29,   // Ф2

        // --- Сила призывов (заявка Макса 2026-07-29, ГДД «Статы» §На будущее) ---
        // Две ручки, а не одна: предметы и эффекты должны усиливать живучесть призывов отдельно от их
        // урона. Множители вокруг 1.0, применяются к базе ассета призванного юнита при его сборке.
        SummonHealthEff = 30,   // PercentMult, старт 1.0 — множитель MaxHP призыва
        SummonDamageEff = 31,   // PercentMult, старт 1.0 — множитель AutoAttackDamage призыва

        // --- Скорость набора ресурса (решение Макса 2026-07-31) ---
        // Слагаемое к глобальной базе StatsConfig._resourceRegenPerSecond, ДО множителя ResourceGainEff.
        // Заведено под мана-дрейн гоблина-проказника: заявка звучала как «-4 единицы», а множителем
        // «-4 из 5» выражается только пока база одинакова у всех — на первом же ките с другой базой
        // множитель и плоская дельта расходятся. Цена решения названа прямо: реген перестал быть
        // «одинаковым у всех» (решение 2026-07-27), теперь одинакова только БАЗА.
        ResourceRegenFlat = 32,

        // --- Стартовый запас здоровья (решение Макса 2026-08-21, под систему ран) ---
        // ДОЛЯ от MaxHP на входе в бой, а не абсолют: старт 1.0, рана «Треснувшее ребро» кладёт
        // PercentMult ×0.7 и боец выходит на арену с 70% своего потолка.
        // Почему доля, хотя сосед StartResource — абсолют: у ресурса потолок задаётся китом и стоит на
        // месте, а MaxHP у нас двигают класс, вид, Судьба, предметы и пассивки — абсолютный «старт 84 HP»
        // разошёлся бы с потолком на первом же баффе, и рана била бы то сильнее, то слабее. Доля от
        // потолка означает ровно то, что обещает карточка раны, при любом MaxHP.
        // Механика различима только там, где есть лечение: срезанный максимум не отыгрывается ничем,
        // срезанный старт отыгрывается хилом ценой маны и времени (ГДД injury-catalogue §3).
        StartHpPct = 33,       // [Ф1] доля 0..1, старт 1.0
    }
}
