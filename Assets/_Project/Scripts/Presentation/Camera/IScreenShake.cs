namespace Guildmaster.Presentation
{
    /// <summary>
    /// Тряска боевой камеры по запросу режиссёра (<c>CombatFeelDirector</c>). За интерфейсом — чтобы боевая
    /// логика не знала про камеру.
    /// <para>Реализация одна и ОБЯЗАТЕЛЬНА: <c>CameraModeController</c> из мировой сцены. Прежний докстринг
    /// обещал заглушку «если рига в сцене нет» — заглушка существовала, но не регистрировалась нигде, то есть
    /// обещание было ложным: без рига падала инъекция всей ветки. Нет рига — это баг разводки сцены, и он
    /// должен падать, а не тихо отключать половину джуса (аудит фолбэков 2026-07-26, п.5).</para>
    /// </summary>
    public interface IScreenShake
    {
        /// <summary>Тряхнуть камеру. <paramref name="intensity"/> 0..1 (клампится); удары складываются вверх (берётся максимум).</summary>
        void Shake(float intensity);

        /// <summary>Мгновенно снять остаточную тряску (перезапуск боя). Не <c>Reset</c> — то магический колбэк MonoBehaviour.</summary>
        void ResetShake();
    }
}
