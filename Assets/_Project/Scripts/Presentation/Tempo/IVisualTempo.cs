namespace Guildmaster.Presentation.Tempo
{
    /// <summary>
    /// ЕДИНЫЙ такт визуала: общий метроном, от которого пляшут все ритмичные анимации — биение доступных
    /// узлов карты, волна по дорожкам, пульсация подсветок. Смысл в том, чтобы они шли не каждая в своём
    /// случайном темпе, а как один организм.
    /// </summary>
    /// <remarks>
    /// Почему за интерфейсом: сейчас такт считается от часов, но источником должна стать МУЗЫКА (FMOD умеет
    /// отдавать позицию и маркеры). Индустрия на этом обжигалась — привязка к таймеру в коде означает, что
    /// смена трека ломает все тайминги; привязка к источнику такта переживает её. Подменим реализацию,
    /// визуал не тронем.
    /// <para>Анимации считают время НЕ в секундах, а в долях: тогда смена темпа меняет их скорость сама.</para>
    /// </remarks>
    public interface IVisualTempo
    {
        /// <summary>Темп, ударов в минуту.</summary>
        float Bpm { get; }

        /// <summary>Длительность одной доли в секундах.</summary>
        float BeatDuration { get; }

        /// <summary>
        /// Фаза внутри доли: 0 в начале, стремится к 1 в конце. <paramref name="division"/> — какая доля:
        /// 1 = целая, 0.5 = половина (вдвое чаще), 2 = два такта (вдвое реже).
        /// </summary>
        float Phase(float division = 1f);

        /// <summary>
        /// Мягкая огибающая доли: 0 → 1 → 0 за такт. Готовый множитель для «дышащих» эффектов, чтобы
        /// каждый вызывающий не писал свой синус и не разъезжался по фазе с остальными.
        /// </summary>
        float Swell(float division = 1f);
    }
}
