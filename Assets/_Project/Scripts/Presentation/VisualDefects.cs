using System.Collections.Generic;
using UnityEngine;

namespace Guildmaster.Presentation
{
    /// <summary>
    /// Крик о том, чего показу НЕ ХВАТИЛО: разметки в клипе, части тела, префаба эффекта. Один ключ —
    /// один крик за прогон: дефект контента обязан быть услышан, но повторяться он будет каждый удар.
    /// </summary>
    /// <remarks>
    /// <b>Почему это отдельный шов, а не <c>Debug.LogError</c> по месту.</b> Нехватка данных для визуала
    /// молчит по своей природе: эффект просто не появляется, а «не появился» и «так задумано» на экране
    /// выглядят одинаково. Поэтому недостающее объявляется дефектом ЯВНО, с указанием следствия — что
    /// именно игрок теперь не увидит, — и с ключом, по которому одно и то же не спамит по кадру.
    /// <para>
    /// Ключ — это ФАКТ, а не носитель: «клип X не размечен» говорится один раз на клип, а не на каждого
    /// из восьми юнитов, которые его играют. Иначе крик тонет в собственном эхе.
    /// </para>
    /// <para>
    /// Уровень — <c>LogError</c> намеренно (требование Макса 03.08.2026): предупреждение в консоли Unity
    /// живёт рядом с чужим шумом и читается как «так бывает». Здесь не бывает: показ заявляет удар, а
    /// нарисовать его нечем.
    /// </para>
    /// </remarks>
    public static class VisualDefects
    {
        private static readonly HashSet<string> Said = new HashSet<string>();

        /// <summary>
        /// Сказать о дефекте один раз. <paramref name="key"/> — сам факт («клип такой-то без разметки»),
        /// <paramref name="context"/> — объект, на который кликают из консоли.
        /// </summary>
        public static void Report(string key, string message, Object context = null)
        {
            if (!Said.Add(key)) return;
            Debug.LogError(message, context);
        }

        /// <summary>
        /// Забыть сказанное. Зовётся на старте боя: дефект нового боя обязан прозвучать, даже если о нём
        /// уже говорили в прошлом — иначе после первой же сцены консоль замолчит на всю сессию.
        /// </summary>
        public static void Reset() => Said.Clear();
    }
}
