namespace Guildmaster.Presentation.Body
{
    /// <summary>
    /// Роль части тела для АДРЕСНОГО свечения (телеграф каста, реф SAO): светится часть-ИСТОЧНИК приёма —
    /// оружие, щит, конечность, — а не всё тело. Флаги, потому что маска свечения
    /// <see cref="BodyVisualState.GlowRoles"/> может включать несколько ролей разом (удар щитом плюс клинком).
    /// <see cref="Body"/> — обычная часть, которая по умолчанию не светится.
    /// </summary>
    [System.Flags]
    public enum PartRole
    {
        None   = 0,
        Body   = 1,
        Weapon = 2,   // меч, посох, лук, коготь — всё, чем наносят приём
        Shield = 4,
        Limb   = 8,   // конечность-источник безоружного удара: кулак, нога
    }
}
