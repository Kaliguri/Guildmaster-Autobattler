namespace Guildmaster.Presentation.Body
{
    /// <summary>Сторона тела, которой принадлежит часть. <see cref="None"/> — часть непарная (торс, голова).</summary>
    public enum BodySide
    {
        None  = 0,
        Left  = 1,
        Right = 2,
    }

    /// <summary>
    /// Рука (или руки), которой держат предмет. Флаги: двуручный предмет занимает ОБЕ и потому отвечает
    /// на запрос по любой из них — «в левой и правой одно и то же».
    /// </summary>
    /// <remarks>
    /// Двуручность выражена слотом, а не отдельным флагом рядом с ним, чтобы её нельзя было представить
    /// двумя записями. Копьё — один спрайт в одном хвате, к которому анимация тянет вторую кисть; будь оно
    /// двумя предметами, свечение зажглось бы дважды по одному древку, а «дай оружие» вернуло бы два.
    /// </remarks>
    [System.Flags]
    public enum HandSlot
    {
        None  = 0,
        Left  = 1,
        Right = 2,
        Both  = Left | Right,
    }

    /// <summary>
    /// Чем предмет в руке является в бою: <see cref="Weapon"/> — всё, чем наносят приём (меч, посох, лук,
    /// коготь), <see cref="Shield"/> — то, чем закрываются и бьют щитовыми приёмами. <see cref="None"/> —
    /// часть тела, а не предмет.
    /// </summary>
    /// <remarks>
    /// Тип НЕ выводится из геометрии и не угадывается по имени спрайта: посох от факела, баклер от книги
    /// формой не отличаются. Это авторский факт, и его владелец — метка <see cref="UnitHeldItem"/> на кости
    /// предмета. До неё тип угадывал риг-профиль (<c>sprite.name.Contains("shield")</c>) — на первом же
    /// новом предмете это соврало бы молча.
    /// </remarks>
    public enum HeldKind
    {
        None   = 0,
        Weapon = 1,
        Shield = 2,
    }
}
