namespace Guildmaster.Game.Session
{
    /// <summary>
    /// Кем этот клиент участвует в игровом сеансе. Роль выбирает СОСТАВ сессии (её инсталлер), а не
    /// проверяется ветвлением на каждом вызове.
    /// </summary>
    /// <remarks>
    /// Роль живёт в Сессии, а не в бою: она про владение состоянием и сейвом, а бой — про арену. Один и
    /// тот же боевой скоуп собирается и у владельца, и у гостя; разница между ними в том, кто состояние
    /// ДЕРЖИТ (решение Макса 02.08.2026, [[scope-hierarchy-decision]]).
    /// </remarks>
    public enum SessionRole
    {
        /// <summary>Играем в своём сейве: состояние забега держим и пишем мы.</summary>
        Owner = 0,

        /// <summary>Играем в чужом сейве: состояние приходит по сети, писать его нам нечем и некуда.</summary>
        Guest = 1,
    }
}
