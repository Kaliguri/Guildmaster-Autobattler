using VContainer.Unity;

namespace Guildmaster.Game.Services
{
    /// <summary>
    /// Боевой «цикл» гостя: тика нет, есть только требование к отставанию показа.
    /// </summary>
    /// <remarks>
    /// <b>Гость своей симуляции не тикает вовсе</b> — ни одного шага, ни одного снятого кадра: он
    /// затёр бы присланную ленту своей пустой ареной. Поэтому у него не «цикл с выключенным тиком», а
    /// другой класс: состав выбирает роль сеанса, и ветки «а мы точно гость?» внутри горячего цикла
    /// больше нет.
    /// <para><b>Отставание постоянное, без оглядки на фазу боя,</b> и это не упрощение. Лента гостя
    /// пополняется исключительно тогда, когда у хоста идёт бой: вне боя фронт хостовой ленты стоит на
    /// месте, раздавать нечего, и чанки не уходят. Значит растущая лента и есть «бой идёт», а
    /// спрашивать об этом местные часы бессмысленно — их у гостя ведёт флоу, которого у него нет.</para>
    /// <para><b>Лаг тот же, что у хоста, намеренно:</b> хост показывает <c>фронт − окно</c>, и гость,
    /// показывающий свой фронт вплотную, увидел бы бой на десять секунд раньше напарника. Общий лаг
    /// сводит обе картинки к одному моменту боя с точностью до задержки сети.</para>
    /// </remarks>
    public sealed class GuestPlaybackLoop : ITickable
    {
        private readonly Combat.Tape.BattleTapePlayback _playback;

        public GuestPlaybackLoop(Combat.Tape.BattleTapePlayback playback) => _playback = playback;

        public void Tick() => _playback.SetTargetLead(Combat.Tape.BattleTapePlayback.LookaheadTicks);
    }
}
