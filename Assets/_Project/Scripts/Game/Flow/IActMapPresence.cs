namespace Guildmaster.Game.Flow
{
    /// <summary>
    /// Карта акта глазами того, кто её не рисует: показана ли она и надо ли её показать.
    /// </summary>
    /// <remarks>
    /// <b>Существует ради одного шва — сеть против показа мира.</b> Хост объявляет гостю, где идёт
    /// игра, и карта — часть этого ответа: её открывает петля акта, а петли у гостя нет (наход. Макса
    /// 03.08.2026). Но сеанс живёт в своём скоупе и о мире знать не обязан; прямая ссылка на
    /// <see cref="WorldMapController"/> тянула бы в сеанс весь показ карты вместе с презентацией и
    /// подписками — что и выяснилось сразу, как только состав сеанса захотели собрать в тесте.
    /// <para>Трёх членов достаточно: спросить, объявить, перечитать. Всё остальное — выбор узла,
    /// подсветка доступных, камера — принадлежит петле забега, и сети там делать нечего.</para>
    /// </remarks>
    public interface IActMapPresence
    {
        /// <summary>Показана ли карта прямо сейчас. Хост объявляет это гостю, чтобы тот шёл следом.</summary>
        bool IsShown { get; }

        /// <summary>
        /// Показать или скрыть карту. Данных для отрисовки может ещё не быть — просьба при этом
        /// остаётся в силе (см. <see cref="Refresh"/>), а не гаснет молча.
        /// </summary>
        void SetVisible(bool visible);

        /// <summary>Состояние забега изменилось — перерисовать карту, если её просили показать.</summary>
        void Refresh();
    }
}
