using System;
using System.Collections.Generic;
using Guildmaster.Guild;

namespace Guildmaster.Game.Flow
{
    /// <summary>
    /// Карта акта глазами того, кто её не рисует: показана ли она и надо ли её показать.
    /// </summary>
    /// <remarks>
    /// <b>Существует ради одного шва — сеть против показа мира.</b> Хост объявляет гостю, где идёт
    /// игра, и карта — часть этого ответа: её открывает петля акта, а петли у гостя нет (наход. Макса
    /// 03.08.2026). Но сеанс живёт в своём скоупе и о мире знать не обязан; прямая ссылка на
    /// <see cref="WorldMapController"/> тянула бы в сеанс весь показ карты вместе с презентацией и
    /// подписками — что и выяснилось сразу, как только состав сеанса захотели собрать в тесте.
    /// <para><b>Подсветка приехала сюда 04.08.2026, а выбор — нет, и это разные вещи.</b> Здесь стояло
    /// «выбор узла, подсветка доступных и камера принадлежат петле забега, и сети там делать нечего» —
    /// верное, пока гость был зрителем. Решение Макса сделало игроков полноправными, но выбор от этого
    /// не стал сетевым: клик обеих сторон уходит КОМАНДОЙ в шину забега, а сюда попало только «какие
    /// узлы сейчас горят». Камера и раскладка узлов по-прежнему не здесь.</para>
    /// <para><b>Ни список достижимого, ни момент ожидания шов не переносит:</b> и то и другое выводится
    /// из состояния — <see cref="MapTraversal.AvailableNext"/> и «поле входа пусто». Обе стороны
    /// считают их сами, каждая по своему снимку карты; присланные, они стали бы вторым владельцем.</para>
    /// </remarks>
    public interface IActMapPresence
    {
        /// <summary>Показана ли карта прямо сейчас. Хост объявляет это гостю, чтобы тот шёл следом.</summary>
        bool IsShown { get; }

        /// <summary>
        /// Показать или скрыть карту. Данных для отрисовки может ещё не быть — просьба при этом
        /// остаётся в силе (см. <see cref="Refresh"/>), а не гаснет молча.
        /// </summary>
        void SetVisible(bool visible);

        /// <summary>Состояние забега изменилось — перерисовать карту, если её просили показать.</summary>
        void Refresh();

        /// <summary>
        /// Ждём ли сейчас выбор узла. Хост объявляет это гостю: узлы горят только в этот момент, а до
        /// него карту можно открыть, но гореть на ней нечему.
        /// </summary>
        bool IsChoosing { get; }

        /// <summary>
        /// Зажечь эти узлы: по ним можно кликать. Клик уходит командой в шину — кому именно отвечать на
        /// него, карта не знает и знать не должна.
        /// </summary>
        /// <param name="show">
        /// Открыть карту заодно. <c>false</c> — не открывать: у гостя её открытость объявлена отдельным
        /// полем, и второй хозяин видимости спорил бы с первым.
        /// </param>
        void BeginChoose(IReadOnlyList<MapNode> available, bool show = true);

        /// <summary>Узлы гаснут: выбирать больше нечего.</summary>
        void EndChoose();
    }
}
