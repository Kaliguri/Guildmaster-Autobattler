namespace Guildmaster.Game.Flow
{
    /// <summary>
    /// Отряд на арене глазами того, кто его не собирает: «поставь заново по текущему забегу».
    /// </summary>
    /// <remarks>
    /// Пара к <see cref="IActMapPresence"/> и существует по той же причине: у гостя отряд ставится
    /// вслед за снимком, а сеанс живёт в своём скоупе и о сборке тел знать не обязан. Прямая ссылка на
    /// <see cref="WorldStageController"/> тащила бы в сеанс сборщик тел, контент-базу и сцену мира.
    /// </remarks>
    public interface IPartyStage
    {
        /// <summary>
        /// Поставить отряд забега на арену заново. Забега нет — арена очищается: в главном меню отряду
        /// стоять негде и не с чего.
        /// </summary>
        void PlaceParty();
    }
}
