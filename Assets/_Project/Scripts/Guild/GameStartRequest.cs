namespace Guildmaster.Guild
{
    /// <summary>
    /// Во что игрок собрался играть. Три режима, других пока нет.
    /// </summary>
    /// <remarks>
    /// <b>Это не то же самое, что <c>ActivityKind</c></b>, и различие намеренное. Вид занятия отвечает
    /// на вопрос «где мы сейчас», а этот тип — на вопрос «что заказал игрок в меню». PvP и Ристалище
    /// разворачиваются в одно и то же занятие с разными ограничениями (см. <c>ActivitySetup.Pvp</c>),
    /// но в меню это два разных пункта, и сводить их в один нельзя: игрок выбирает не устройство
    /// движка, а игру.
    /// </remarks>
    public enum GameMode
    {
        /// <summary>Забег по акту: карта, узлы, награды, сейв гильдии.</summary>
        Campaign = 0,

        /// <summary>Площадка: свободный состав, свободная расстановка, ни карты, ни сейва.</summary>
        ProvingGrounds = 1,

        /// <summary>Матч: та же площадка, но чужой строй скрыт и расставлять можно только своих.</summary>
        Pvp = 2,
    }

    /// <summary>
    /// Заказ на вход в игру, собранный игроком в меню: режим, дом и открытость для друзей.
    /// </summary>
    /// <remarks>
    /// <b>Роль и лобби известны в момент рождения сеанса</b> (модель Макса 02.08.2026): игрок жмёт
    /// «Создать игру», и тем же кликом решает, пускать ли к себе. Прежде сеанс открывался на буте
    /// ролью владельца по умолчанию, а кооп был отдельным входом рядом с игрой — то есть две двери
    /// вели в одно и то же, и порядок читался наизнанку.
    /// <para><b>Гильдия и есть слот сохранения</b> (ТЗ [[save-system]] §3), поэтому пары
    /// «Начать / Продолжить» здесь нет: игрок выбирает дом, а забег в нём либо уже идёт, либо
    /// начинается. Пустой <see cref="GuildId"/> значит «новая гильдия» — для Кампании, и «не
    /// применимо» для остальных режимов: у площадки дома нет.</para>
    /// </remarks>
    public readonly struct GameStartRequest
    {
        public readonly GameMode Mode;

        /// <summary>Гильдия, в которой играем. Пусто — завести новую (или режим без дома).</summary>
        public readonly string GuildId;

        /// <summary>Поднять лобби Steam, чтобы к нам могли присоединиться.</summary>
        /// <remarks>
        /// Свойство СЕАНСА, а не режима: в кооп одинаково пускаются и Кампания, и площадка, и матч.
        /// Ветка «кооп-режим» рядом с обычными завела бы второго владельца у каждого режима сразу.
        /// </remarks>
        public readonly bool OnlineLobby;

        public GameStartRequest(GameMode mode, string guildId = null, bool onlineLobby = true)
        {
            Mode        = mode;
            GuildId     = guildId ?? string.Empty;
            OnlineLobby = onlineLobby;
        }

        /// <summary>Заводим новый дом, а не продолжаем существующий.</summary>
        public bool IsNewGuild => string.IsNullOrEmpty(GuildId);

        /// <summary>
        /// Ристалище, заказанное дев-командой: без лобби и без дома.
        /// </summary>
        /// <remarks>
        /// Живёт рядом с типом, а не у презентера или роутера, потому что зовут его оба: команду
        /// <c>gm_proving_grounds</c> обрабатывают и «меню уже на экране», и «меню ещё не открылось».
        /// Две копии одного заказа разъехались бы на первой же правке — например, стоило бы кому-то
        /// одному включить лобби.
        /// <para>Лобби выключено намеренно, в отличие от входа игроком: команду зовут, когда игра
        /// куда-то не дошла, и поднимать при этом сессию для друзей — лишний внешний вызов в отладке.</para>
        /// </remarks>
        public static GameStartRequest DevProvingGrounds =>
            new(GameMode.ProvingGrounds, onlineLobby: false);
    }
}
