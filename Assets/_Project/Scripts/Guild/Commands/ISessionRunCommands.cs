    /// локальная шина (<see cref="RunCommandBus"/> — применяет и пишет в лог), у гостя — отправка интента
    /// хосту. Вызывающие не различают их вовсе: они и так написаны под ответ «принято локально», а не
    /// «вышло или нет».</para>
    /// </remarks>
    public interface ISessionRunCommands : IRunCommands
