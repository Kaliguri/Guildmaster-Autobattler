namespace Guildmaster.Guild
{
    /// <summary>
    /// Чтение durable-состояния забега для тех, кто живёт ДОЛЬШЕ него: корневого интерфейса, мира,
    /// показа. Отдаёт ровно то, что есть сейчас, и ничего не обещает про «потом».
    /// </summary>
    /// <remarks>
    /// <b>Шов read-only не для красоты.</b> Владелец состояния (<see cref="RunStateService"/>) живёт в
    /// скоупе Сессии и умирает вместе с ней; долгожители не могут держать на него ссылку — она протухнет
    /// при первой же смене владельца сейва (вход в кооп гостем, смена профиля). Поэтому наружу торчит
    /// вопрос «что в забеге сейчас», а отвечает на него роутер.
    /// <para><b>Писать через этот шов нельзя намеренно:</b> запись в забег обязана попасть в лог команд
    /// (<c>IRunCommands</c>), иначе реконнект и аудит увидят состояние без причины. Читателю снаружи
    /// сессии писать некуда — у него и команд-то нет.</para>
    /// <para><c>null</c> — законный ответ: вне забега состояния нет, и это не отказ, а факт.</para>
    /// </remarks>
    public interface IRunStateView
    {
        /// <summary>Состояние текущего забега или <c>null</c>, если забега нет.</summary>
        RunState Current { get; }
    }
}
