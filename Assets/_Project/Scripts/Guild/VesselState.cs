using System;

namespace Guildmaster.Guild
{
    /// <summary>
    /// Человек гильдии — durable-запись «Сосуда», переживающая забеги (ГДД
    /// [[gdd/30-run-meta/guild-development|Развитие гильдии]] §Люди дома).
    /// <para><b>Что здесь есть и чего здесь принципиально нет.</b> Здесь лежит то, что делает человека
    /// собой между походами: сид рождения, имя, перки, счёт походов, как он закончил. Здесь НЕТ ни
    /// уровней, ни статов, ни Судьбы — всё это живёт внутри забега и в конце сгорает (реш. 2026-07-15/25,
    /// 2026-07-27/17). Нет и боевой мощи: она приходит из Мементо, а не от человека.</para>
    /// <para><b>Летопись тоже не здесь</b>, а в <see cref="GuildBook"/>: записи принадлежат дому, поэтому
    /// память о человеке живёт и после его гибели (реш. 2026-07-27/19).</para>
    /// </summary>
    [Serializable]
    public sealed class VesselState
    {
        /// <summary>Идентификатор внутри гильдии. Летопись ссылается на человека этим значением.</summary>
        public string Id = string.Empty;

        /// <summary>
        /// Сид рождения: из него детерминированно разворачивается досье (мечта / характер / байка) и
        /// внешность. Привязка именно к рождению, а не к забегу — иначе личность пересобиралась бы каждый
        /// поход, пока Летопись помнит подвиги (реш. 2026-07-27/21). Меняться не должен никогда.
        /// </summary>
        public long BirthSeed;

        /// <summary>Имя, которое видит игрок. Отдельно от сида: игрок вправе переименовать.</summary>
        public string Name = string.Empty;

        /// <summary>Id прегена, если это кураторский герой; пусто у наёмных. Экземпляр прегена свой у
        /// каждого дома и смертен, само открытие потерять нельзя (реш. 2026-07-27/15).</summary>
        public string PregenId = string.Empty;

        /// <summary>Положительный перк. Фиксируется при найме навсегда (реш. 2026-07-27/18); сменить
        /// можно лишь через «тренировочный пункт», форма которого ещё не выбрана.</summary>
        public string PositiveTraitId = string.Empty;

        /// <summary>Отрицательный перк. Те же правила, что у положительного.</summary>
        public string NegativeTraitId = string.Empty;

        /// <summary>
        /// Сколько ЗАВЕРШЁННЫХ забегов человек пережил (победа или поражение — важно, что вернулся
        /// живым). <b>Ветеран — тот, у кого это больше нуля</b> (реш. 2026-07-27/6): именно ветеранов
        /// пускают в отряд на верхних ступенях возвышения.
        /// </summary>
        public int CompletedRuns;

        /// <summary>Когда пришёл в дом (ISO-8601 UTC) — для сортировки казарм и строк Летописи.</summary>
        public string JoinedUtc = string.Empty;

        /// <summary>
        /// Куплен ли как готовый ветеран. Такой наём открывается после того, как дом потерял достаточно
        /// своих (реш. 2026-07-27/7), и несёт штраф к статам — см. <see cref="HiredPenaltyRunsLeft"/>.
        /// </summary>
        public bool HiredVeteran;

        /// <summary>
        /// Сколько ещё завершённых забегов купленный ветеран носит штраф (−3% к статам). Ноль = штрафа
        /// нет. Штраф намеренно мелкий: зудит, что история куплена, а не прожита, но бой не ломает; и
        /// сходит со службой, потому что наёмник прирастает к дому.
        /// </summary>
        public int HiredPenaltyRunsLeft;

        /// <summary>
        /// Жив ли. Мёртвые не удаляются, а переезжают в <see cref="GuildBook.Fallen"/> целиком, без
        /// усечения: память о человеке деградировать не должна (реш. 2026-07-27/19).
        /// </summary>
        public bool IsAlive = true;
    }
}
