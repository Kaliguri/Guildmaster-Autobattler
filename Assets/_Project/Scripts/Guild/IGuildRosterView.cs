using System.Collections.Generic;

namespace Guildmaster.Guild
{
    /// <summary>
    /// Чтение людей ДОМА для тех, кто живёт в забеге. Забег ссылается на человека строковым id
    /// (<c>RosterSlot.VesselId</c>), а сам человек принадлежит гильдии и переживает поход.
    /// </summary>
    /// <remarks>
    /// <b>Зачем отдельный интерфейс, а не метод в <c>IProfileService</c>.</b> Профиль объявлен в
    /// <c>Guildmaster.Core</c>, а <c>VesselState</c> и <c>GuildState</c> живут в <c>Guildmaster.Guild</c>:
    /// ядро про гильдию не знает и знать не должно. Отдать ростер через профиль значило бы затащить
    /// типы дома в ядро — то есть заплатить слоями за одно свойство.
    /// <para><b>Только чтение.</b> Наём, гибель и переименование меняют дом, а изменения дома идут
    /// своей дорогой (сейв гильдии), как изменения забега идут командами. Читателю здесь писать
    /// нечего.</para>
    /// <para>Пустой список — законный ответ: дом без людей бывает, и это факт, а не отказ.</para>
    /// </remarks>
    public interface IGuildRosterView
    {
        /// <summary>Живые люди активного дома. Пусто, если дома нет или он ещё никого не принял.</summary>
        IReadOnlyList<VesselState> Roster { get; }
    }
}
