namespace Guildmaster.UI
{
    /// <summary>
    /// Тип экрана определяет ЕГО ПОВЕДЕНИЕ в навигаторе — вместо CSS-классов-флагов и параметров Push
    /// (см. план UI-реворка II.2). По этому типу навигатор вычисляет видимость нижних экранов и глушение
    /// геймплейного ввода — единый источник вместо ручной синхронизации.
    /// </summary>
    public enum ScreenKind
    {
        /// <summary>Полноэкранный непрозрачный: глушит геймплей, прячет экран под собой (карта, магазин, ивент, награда, главное меню).</summary>
        Page,

        /// <summary>Поверх со scrim: глушит геймплей, НЕ прячет нижний экран структурно (пауза, настройки, подтверждение).</summary>
        Modal,

        /// <summary>Прозрачный: НЕ глушит геймплей (мир под ним жив через PointerOverUI), НЕ прячет нижний (инвентарь, тест-зона).</summary>
        Sheet,
    }
}
